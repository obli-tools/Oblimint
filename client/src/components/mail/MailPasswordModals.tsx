/**
 * Shows a generated password ONCE (MA4): the parent keeps it only while this
 * dialog is open and drops it in `onClose` — it is never stored elsewhere.
 */
export function PasswordRevealModal({ password, address, onClose }: { password: string | null; address: string; onClose: () => void }) {
  const { t } = useTranslation();
  const [shown, setShown] = useState(true);
  useEffect(() => { if (password) setShown(true); }, [password]);
  return (
    <Modal
      open={password !== null}
      onClose={onClose}
      title={t('mail.password.revealTitle') || 'Generated password'}
      icon={<KeyRound className="h-4 w-4 text-accent" />}
      size="sm"
      phoneLayout="sheet"
      closeOnBackdrop={false}
      footer={<Button size="sm" onClick={onClose}>{t('mail.password.revealDone') || 'I have saved it'}</Button>}
    >
      <div className="space-y-3">
        <p className="text-sm text-text-secondary">
          {t('mail.password.revealFor', { address, defaultValue: 'Password of {{address}}:' })}
        </p>
        <div className="flex items-center gap-1 rounded-lg bg-bg-primary px-3 py-2">
          <code className="min-w-0 flex-1 break-all font-mono text-sm text-text-primary">
            {shown ? password : '•'.repeat(Math.min(24, password?.length ?? 0))}
          </code>
          <IconButton
            label={shown ? (t('mail.password.hide') || 'Hide') : (t('mail.password.show') || 'Show')}
            icon={shown ? <EyeOff size={13} /> : <Eye size={13} />}
            size="sm"
            onClick={() => setShown((v) => !v)}
          />
          {password && <CopyButton text={password} />}
        </div>
        <p className="flex items-start gap-2 rounded-md bg-amber-400/5 p-2 text-xs text-amber-400">
          <AlertTriangle size={13} className="mt-0.5 shrink-0" />
          {t('mail.password.revealWarning') || 'It is shown only now: the panel keeps only a hash. Copy it into the mail client or a password manager.'}
        </p>
      </div>
    </Modal>
  );
}

type PwMode = 'generate' | 'enter' | 'import';

/** Password field + generate / import choice, shared by the creation and change dialogs. */
export function PasswordChoice({ mode, onMode, password, onPassword, hash, onHash, staff, idPrefix }: {
  mode: PwMode;
  onMode: (m: PwMode) => void;
  password: string;
  onPassword: (v: string) => void;
  hash: string;
  onHash: (v: string) => void;
  /** Import of a hash: staff only (hidden for client users; the server refuses it too). */
  staff: boolean;
  idPrefix: string;
}) {
  const { t } = useTranslation();
  const [visible, setVisible] = useState(false);
  const issue = mode === 'enter' && password ? mailPasswordIssue(password) : null;
  const issueText = issue === 'tooShort'
    ? (t('mail.password.tooShort') || 'At least 10 characters.')
    : issue === 'tooLong' ? (t('mail.password.tooLong') || '256 bytes at most.') : issue === 'control' ? (t('mail.password.control') || 'No control character.') : null;
  return (
    <div className="space-y-2">
      <SegmentedTabs<PwMode>
        size="sm"
        value={mode}
        onChange={onMode}
        tabs={[
          { id: 'generate', label: t('mail.password.modeGenerate') || 'Generate', icon: <Wand2 size={12} /> },
          { id: 'enter', label: t('mail.password.modeEnter') || 'Choose' },
          { id: 'import', label: t('mail.password.modeImport') || 'Import a hash', hidden: !staff },
        ]}
      />
      {mode === 'generate' && (
        <p className="text-xs text-text-muted">{t('mail.password.generateHint') || 'A strong password is generated by the server and shown once.'}</p>
      )}
      {mode === 'enter' && (
        <div>
          <label className={labelCls} htmlFor={`${idPrefix}-pw`}>{t('mail.password.label') || 'Password'}</label>
          <div className="relative">
            <input
              id={`${idPrefix}-pw`}
              type={visible ? 'text' : 'password'}
              value={password}
              onChange={(e) => onPassword(e.target.value)}
              autoComplete="new-password"
              className={cn(inputCls, 'pr-10 font-mono', issue && 'ring-2 ring-status-down/50')}
            />
            <IconButton
              label={visible ? (t('mail.password.hide') || 'Hide') : (t('mail.password.show') || 'Show')}
              icon={visible ? <EyeOff size={13} /> : <Eye size={13} />}
              size="sm"
              className="absolute right-1.5 top-1/2 -translate-y-1/2"
              onClick={() => setVisible((v) => !v)}
            />
          </div>
          {issueText && <p className="mt-1 text-xs text-status-down">{issueText}</p>}
        </div>
      )}
      {mode === 'import' && staff && (
        <div>
          <label className={labelCls} htmlFor={`${idPrefix}-hash`}>{t('mail.password.hashLabel') || 'Password hash'}</label>
          <input
            id={`${idPrefix}-hash`}
            value={hash}
            onChange={(e) => onHash(e.target.value)}
            placeholder="{SHA512-CRYPT}$6$… / $1$…"
            autoCapitalize="off" autoCorrect="off" spellCheck={false} autoComplete="off"
            className={cn(inputCls, 'font-mono')}
          />
          <p className="mt-1 text-xs text-text-muted">{t('mail.password.hashHint') || 'Migration: the hash is kept as is (SHA512/256-CRYPT, MD5-CRYPT, BLF-CRYPT, SSHA*), the mailbox keeps its password.'}</p>
        </div>
      )}
    </div>
  );
}

/** Whether the password part of a form can be submitted. */
export function passwordChoiceValid(mode: PwMode, password: string, hash: string): boolean {
  if (mode === 'enter') return !!password && mailPasswordIssue(password) === null;
  if (mode === 'import') return hash.trim().length > 0;
  return true;
}

export type { PwMode };

/** Change the password of a mailbox (generated → shown once by the caller through onGenerated). */
export function MailPasswordModal({ open, mailboxId, address, staff, onClose, onDone }: {
  open: boolean;
  mailboxId: number;
  address: string;
  staff: boolean;
  onClose: () => void;
  /** generated = the password to show once (null when the caller chose it / imported a hash). */
  onDone: (generated: string | null) => void;
}) {
  const { t } = useTranslation();
  const [mode, setMode] = useState<PwMode>('generate');
  const [password, setPassword] = useState('');
  const [hash, setHash] = useState('');
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState('');

  // Nothing typed survives the dialog (MA4).
  useEffect(() => { if (!open) { setPassword(''); setHash(''); setMode('generate'); setError(''); } }, [open]);

  const submit = async () => {
    if (!passwordChoiceValid(mode, password, hash)) return;
    setSaving(true);
    setError('');
    try {
      const res = await mailApi.setPassword(mailboxId, mode === 'enter' ? { password } : mode === 'import' ? { passwordHash: hash.trim() } : {});
      setPassword('');
      setHash('');
      onDone(res.password);
    } catch (err) {
      setError(mailErrorMessage(t, err, t('mail.password.failed') || 'Failed to change the password'));
    } finally {
      setSaving(false);
    }
  };

  return (
    <Modal
      open={open}
      onClose={onClose}
      title={t('mail.password.changeTitle', { address, defaultValue: 'Password of {{address}}' })}
      icon={<KeyRound className="h-4 w-4 text-accent" />}
      size="sm"
      footer={
        <>
          <Button size="sm" variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button>
          <Button size="sm" loading={saving} disabled={!passwordChoiceValid(mode, password, hash)} onClick={() => { void submit(); }}>
            {t('mail.password.change') || 'Change the password'}
          </Button>
        </>
      }
    >
      <div className="space-y-3">
        <PasswordChoice mode={mode} onMode={setMode} password={password} onPassword={setPassword} hash={hash} onHash={setHash} staff={staff} idPrefix="mbpw" />
        <p className="text-xs text-text-muted">{t('mail.password.changeHint') || 'Open mail clients and webmail sessions will have to sign in again.'}</p>
        {error && <p className="whitespace-pre-line text-xs text-status-down">{error}</p>}
      </div>
    </Modal>
  );
}
