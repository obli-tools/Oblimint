// Structure editing of the explorer: forms build a STRUCTURED request, the
// server generates the DDL (preview), the user reads / edits it, then runs it.
// Unchanged, the server regenerates and runs it (DDL path, audited as such);
// edited by hand, it runs as a console statement under the same SQL user.

const inputCls = 'w-full rounded-lg bg-bg-tertiary px-2.5 py-1.5 text-[13px] text-text-primary outline-none ring-1 ring-white/[0.06] focus:ring-accent';
const labelCls = 'mb-1 block text-[11px] font-medium uppercase tracking-[0.08em] text-text-muted';

const TYPES: Record<DbFamily, string[]> = {
  mysql: ['int', 'bigint', 'smallint', 'tinyint(1)', 'decimal(10,2)', 'double', 'varchar(255)', 'char(36)', 'text', 'mediumtext', 'longtext', 'json', 'date', 'datetime', 'timestamp', 'time', 'blob', 'enum(\'a\',\'b\')'],
  postgresql: ['integer', 'bigint', 'smallint', 'numeric(10,2)', 'double precision', 'boolean', 'varchar(255)', 'text', 'uuid', 'jsonb', 'json', 'date', 'timestamp', 'timestamptz', 'time', 'bytea', 'text[]'],
};

export function ddlText(statements: string[]): string {
  return statements.map((s) => `${s};`).join('\n\n');
}

/** Preview of a structured request: warnings, editable DDL, run. */
export function DdlPreviewModal({ instanceId, dbId, request, title, onClose, onDone }: {
  instanceId: number;
  dbId: number;
  request: DbxDdlRequest;
  title: string;
  onClose: () => void;
  onDone: () => void;
}) {
  const { t } = useTranslation();
  const confirm = useConfirm();
  const [preview, setPreview] = useState<DbxDdlPreview | null>(null);
  const [text, setText] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    let live = true;
    dbExplorerApi.ddlPreview(instanceId, dbId, request)
      .then((p) => { if (live) { setPreview(p); setText(ddlText(p.statements)); } })
      .catch((err) => { if (live) setError(explorerError(err)); });
    return () => { live = false; };
  }, [instanceId, dbId, request]);

  const edited = preview !== null && text.trim() !== ddlText(preview.statements).trim();
  const run = async () => {
    if (!preview) return;
    if (edited && !(await confirm({
      title: t('dbx.ddl.editedTitle') || 'Edited DDL',
      message: t('dbx.ddl.editedMessage') || 'You changed the generated statements: they run as console statements, as written.',
      confirmLabel: t('dbx.console.run') || 'Run',
    }))) return;
    setBusy(true);
    setError(null);
    try {
      const r = edited ? await dbExplorerApi.query(instanceId, dbId, text) : await dbExplorerApi.ddlApply(instanceId, dbId, request);
      const failed = r.results.find((x) => x.error);
      if (failed) { setError(`${failed.statement.slice(0, 200)}\n→ ${failed.error}`); return; }
      toast.success(t('dbx.ddl.done') || 'Structure updated');
      onDone();
      onClose();
    } catch (err) {
      setError(explorerError(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    <Modal open onClose={onClose} size="xl" title={title} icon={<Code2 className="h-4 w-4 text-accent" />} closeOnEscape={false}
      footer={(
        <div className="flex w-full flex-wrap items-center justify-end gap-2">
          {edited && <Pill tone="amber">{t('dbx.ddl.editedPill') || 'edited: runs as a console statement'}</Pill>}
          <Button variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button>
          <Button variant={/^(drop|truncate)/.test(request.op) ? 'danger' : 'primary'} loading={busy} disabled={!preview || !text.trim()} onClick={() => void run()}>
            {t('dbx.ddl.run') || 'Run'}
          </Button>
        </div>
      )}>
      <div className="space-y-3">
        <p className="text-xs text-text-muted">{t('dbx.ddl.previewHint') || 'Generated by the panel from your choices. Read it before running it; you may adjust it.'}</p>
        {preview?.warnings.map((w) => (
          <div key={w.key + w.text} className="flex items-start gap-2 rounded-lg bg-amber-400/10 px-3 py-2 text-xs text-amber-400">
            <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" />{t(`dbx.ddl.warn.${w.key}`, { defaultValue: w.text })}
          </div>
        ))}
        {!preview && !error && <div className="flex justify-center p-6"><LoadingSpinner /></div>}
        {preview && (preview.statements.length
          ? <CodeEditor value={text} onChange={setText} language="sql" minHeight="120px" maxHeight="50vh" ariaLabel="DDL" />
          : <p className="text-sm text-text-muted">{t('dbx.ddl.nothing') || 'Nothing to change.'}</p>)}
        {error && <pre className="whitespace-pre-wrap rounded-lg bg-status-down/10 px-3 py-2 font-mono text-xs text-status-down">{error}</pre>}
      </div>
    </Modal>
  );
}

// ── column form ──────────────────────────────────────────────────────────────

type DefaultMode = 'none' | 'null' | 'literal' | 'expression';

interface ColumnDraft {
  name: string;
  type: string;
  nullable: boolean;
  defaultMode: DefaultMode;
  defaultValue: string;
  autoIncrement: boolean;
  comment: string;
}

const isExpression = (d: string) => /^(current_timestamp|now|current_date|current_time|localtimestamp|uuid|gen_random_uuid|true|false|-?[\d.]+)/i.test(d.trim());

export function draftOf(c?: DbxColumn): ColumnDraft {
  if (!c) return { name: '', type: '', nullable: true, defaultMode: 'none', defaultValue: '', autoIncrement: false, comment: '' };
  const serial = c.autoIncrement;
  let defaultMode: DefaultMode = 'none';
  let defaultValue = '';
  if (!serial && c.default !== null) {
    if (/^null$/i.test(c.default)) defaultMode = 'null';
    else {
      const lit = /^'((?:[^']|'')*)'(::[\w\s]+)?$/.exec(c.default);
      if (lit) { defaultMode = 'literal'; defaultValue = lit[1].replace(/''/g, '\''); } else if (isExpression(c.default)) { defaultMode = 'expression'; defaultValue = c.default.replace(/::[\w\s]+$/, ''); } else { defaultMode = 'literal'; defaultValue = c.default; }
    }
  }
  return { name: c.name, type: c.type, nullable: c.nullable, defaultMode, defaultValue, autoIncrement: c.autoIncrement, comment: c.comment ?? '' };
}

export function defOf(d: ColumnDraft): DbxColumnDef {
  const dflt: DbxDefault | null = d.defaultMode === 'none' ? null : d.defaultMode === 'null' ? { kind: 'null' } : { kind: d.defaultMode, value: d.defaultValue };
  return { name: d.name.trim(), type: d.type.trim(), nullable: d.nullable, default: dflt, autoIncrement: d.autoIncrement || undefined, comment: d.comment.trim() || null };
}

function ColumnFields({ family, draft, onChange, compact }: { family: DbFamily; draft: ColumnDraft; onChange: (d: ColumnDraft) => void; compact?: boolean }) {
  const { t } = useTranslation();
  const set = (p: Partial<ColumnDraft>) => onChange({ ...draft, ...p });
  const listId = `dbx-types-${family}`;
  return (
    <div className={compact ? 'grid grid-cols-[1.2fr_1.2fr_auto_auto_1fr_1.2fr] items-center gap-2' : 'grid gap-3 sm:grid-cols-2'}>
      <datalist id={listId}>{TYPES[family].map((x) => <option key={x} value={x} />)}</datalist>
      <div>
        {!compact && <label className={labelCls}>{t('dbx.structure.name') || 'Name'}</label>}
        <input value={draft.name} onChange={(e) => set({ name: e.target.value })} placeholder={t('dbx.structure.name') || 'Name'} className={`${inputCls} font-mono`} autoCapitalize="off" spellCheck={false} />
      </div>
      <div>
        {!compact && <label className={labelCls}>{t('dbx.structure.type') || 'Type'}</label>}
        <input value={draft.type} onChange={(e) => set({ type: e.target.value })} list={listId} placeholder="varchar(255)" className={`${inputCls} font-mono`} autoCapitalize="off" spellCheck={false} />
      </div>
      <label className="inline-flex items-center gap-1.5 text-[12px] text-text-secondary">
        <input type="checkbox" checked={draft.nullable} onChange={(e) => set({ nullable: e.target.checked })} className="accent-[rgb(var(--c-accent))]" />NULL
      </label>
      <label className="inline-flex items-center gap-1.5 text-[12px] text-text-secondary" title={family === 'postgresql' ? 'GENERATED BY DEFAULT AS IDENTITY' : 'AUTO_INCREMENT'}>
        <input type="checkbox" checked={draft.autoIncrement} onChange={(e) => set({ autoIncrement: e.target.checked, ...(e.target.checked ? { defaultMode: 'none' as const } : {}) })} className="accent-[rgb(var(--c-accent))]" />
        {t('dbx.structure.autoIncrement') || 'Auto'}
      </label>
      <div className={compact ? 'flex gap-1' : 'flex gap-2 sm:col-span-2'}>
        <select value={draft.defaultMode} disabled={draft.autoIncrement} onChange={(e) => set({ defaultMode: e.target.value as DefaultMode })} className={`${inputCls} w-auto`} title={t('dbx.structure.default') || 'Default'}>
          <option value="none">{compact ? '—' : (t('dbx.column.noDefault') || 'No default')}</option>
          <option value="null">NULL</option>
          <option value="literal">{t('dbx.column.literal') || 'Value'}</option>
          <option value="expression">{t('dbx.column.expression') || 'Expression'}</option>
        </select>
        {(draft.defaultMode === 'literal' || draft.defaultMode === 'expression') && (
          <input value={draft.defaultValue} onChange={(e) => set({ defaultValue: e.target.value })} list={draft.defaultMode === 'expression' ? 'dbx-default-expr' : undefined}
            placeholder={draft.defaultMode === 'expression' ? 'CURRENT_TIMESTAMP' : ''} className={`${inputCls} font-mono`} />
        )}
        <datalist id="dbx-default-expr">{['CURRENT_TIMESTAMP', 'CURRENT_DATE', family === 'postgresql' ? 'now()' : 'NOW()', family === 'postgresql' ? 'gen_random_uuid()' : 'uuid()', 'true', 'false'].map((x) => <option key={x} value={x} />)}</datalist>
      </div>
      <div className={compact ? '' : 'sm:col-span-2'}>
        {!compact && <label className={labelCls}>{t('dbx.structure.comment') || 'Comment'}</label>}
        <input value={draft.comment} onChange={(e) => set({ comment: e.target.value })} placeholder={t('dbx.structure.comment') || 'Comment'} className={inputCls} />
      </div>
    </div>
  );
}

/** Add a column, or change one (name, type, NULL, default, auto-increment, comment). */
export function ColumnModal({ family, info, column, onClose, onRequest }: {
  family: DbFamily;
  info: DbxTableInfo;
  column?: DbxColumn;
  onClose: () => void;
  onRequest: (r: DbxDdlRequest, title: string) => void;
}) {
  const { t } = useTranslation();
  const [draft, setDraft] = useState<ColumnDraft>(() => draftOf(column));
  const [after, setAfter] = useState<string>('__last');
  const submit = () => {
    const def = defOf(draft);
    if (column) onRequest({ op: 'modifyColumn', table: info.table.id, column: column.name, def }, t('dbx.column.editTitle', { name: column.name, defaultValue: 'Change column {{name}}' }));
    else onRequest({ op: 'addColumn', table: info.table.id, column: def, ...(family === 'mysql' && after !== '__last' ? { after: after === '__first' ? '' : after } : {}) }, t('dbx.column.addTitle') || 'Add a column');
  };
  return (
    <Modal open onClose={onClose} size="lg" title={column ? t('dbx.column.editTitle', { name: column.name, defaultValue: 'Change column {{name}}' }) : (t('dbx.column.addTitle') || 'Add a column')}
      footer={<div className="flex justify-end gap-2"><Button variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button><Button disabled={!draft.name.trim() || !draft.type.trim()} onClick={submit}>{t('dbx.ddl.preview') || 'Preview the DDL'}</Button></div>}>
      <div className="space-y-3">
        <ColumnFields family={family} draft={draft} onChange={setDraft} />
        {!column && family === 'mysql' && (
          <div>
            <label className={labelCls}>{t('dbx.column.position') || 'Position'}</label>
            <select value={after} onChange={(e) => setAfter(e.target.value)} className={inputCls}>
              <option value="__last">{t('dbx.column.last') || 'At the end'}</option>
              <option value="__first">{t('dbx.column.first') || 'First'}</option>
              {info.columns.map((c) => <option key={c.name} value={c.name}>{t('dbx.column.after', { name: c.name, defaultValue: 'After {{name}}' })}</option>)}
            </select>
          </div>
        )}
        {column && family === 'mysql' && <p className="text-[11px] text-text-muted">{t('dbx.ddl.warn.fullRedefinition') || 'The whole column is redefined: attributes not shown here are reset (the collation and ON UPDATE are kept).'}</p>}
      </div>
    </Modal>
  );
}

/** New table: columns, primary key, comment. */
export function CreateTableModal({ family, onClose, onRequest }: { family: DbFamily; onClose: () => void; onRequest: (r: DbxDdlRequest, title: string) => void }) {
  const { t } = useTranslation();
  const [name, setName] = useState('');
  const [comment, setComment] = useState('');
  const [cols, setCols] = useState<ColumnDraft[]>(() => [
    { ...draftOf(), name: 'id', type: family === 'postgresql' ? 'bigint' : 'bigint unsigned', nullable: false, autoIncrement: true },
    { ...draftOf(), name: 'created_at', type: family === 'postgresql' ? 'timestamptz' : 'timestamp', nullable: false, defaultMode: 'expression', defaultValue: 'CURRENT_TIMESTAMP' },
  ]);
  const [pk, setPk] = useState<string[]>(['id']);
  const submit = () => onRequest({
    op: 'createTable', name: name.trim(), columns: cols.map(defOf), primaryKey: pk.filter((p) => cols.some((c) => c.name.trim() === p)), comment: comment.trim() || null,
  }, t('dbx.table.createTitle') || 'New table');
  return (
    <Modal open onClose={onClose} size="2xl" title={t('dbx.table.createTitle') || 'New table'}
      footer={<div className="flex justify-end gap-2"><Button variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button><Button disabled={!name.trim() || !cols.length || cols.some((c) => !c.name.trim() || !c.type.trim())} onClick={submit}>{t('dbx.ddl.preview') || 'Preview the DDL'}</Button></div>}>
      <div className="space-y-3">
        <div className="grid gap-3 sm:grid-cols-2">
          <div><label className={labelCls}>{t('dbx.structure.name') || 'Name'}</label><input value={name} onChange={(e) => setName(e.target.value)} className={`${inputCls} font-mono`} autoFocus autoCapitalize="off" spellCheck={false} /></div>
          <div><label className={labelCls}>{t('dbx.structure.comment') || 'Comment'}</label><input value={comment} onChange={(e) => setComment(e.target.value)} className={inputCls} /></div>
        </div>
        <div className="space-y-2">
          <div className={labelCls}>{t('dbx.structure.columns') || 'Columns'}</div>
          {cols.map((c, i) => (
            <div key={i} className="flex items-center gap-2 rounded-lg bg-bg-primary/40 p-2">
              <label className="inline-flex items-center gap-1 text-[11px] text-amber-400" title={t('dbx.structure.primaryKey') || 'Primary key'}>
                <input type="checkbox" checked={pk.includes(c.name.trim())} onChange={(e) => setPk(e.target.checked ? [...pk, c.name.trim()] : pk.filter((p) => p !== c.name.trim()))} className="accent-[rgb(var(--c-accent))]" />PK
              </label>
              <div className="min-w-0 flex-1"><ColumnFields family={family} draft={c} compact onChange={(d) => setCols(cols.map((x, k) => (k === i ? d : x)))} /></div>
              <IconButton size="sm" variant="danger" label={t('common.delete') || 'Delete'} icon={<Trash2 className="h-4 w-4" />} onClick={() => setCols(cols.filter((_, k) => k !== i))} />
            </div>
          ))}
          <Button size="sm" variant="secondary" onClick={() => setCols([...cols, { ...draftOf(), type: family === 'postgresql' ? 'text' : 'varchar(255)' }])}><Plus className="mr-1 h-3.5 w-3.5" />{t('dbx.column.addTitle') || 'Add a column'}</Button>
        </div>
      </div>
    </Modal>
  );
}

/** New index (unique or not) on columns of the table, in order. */
export function IndexModal({ info, onClose, onRequest }: { info: DbxTableInfo; onClose: () => void; onRequest: (r: DbxDdlRequest, title: string) => void }) {
  const { t } = useTranslation();
  const [cols, setCols] = useState<string[]>([]);
  const [unique, setUnique] = useState(false);
  const [name, setName] = useState('');
  const auto = `${unique ? 'ux' : 'ix'}_${info.table.name}_${cols.join('_')}`.slice(0, 60);
  return (
    <Modal open onClose={onClose} size="md" title={t('dbx.index.addTitle') || 'New index'}
      footer={<div className="flex justify-end gap-2"><Button variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button>
        <Button disabled={!cols.length} onClick={() => onRequest({ op: 'createIndex', table: info.table.id, name: name.trim() || auto, columns: cols, unique }, t('dbx.index.addTitle') || 'New index')}>{t('dbx.ddl.preview') || 'Preview the DDL'}</Button></div>}>
      <div className="space-y-3">
        <div><label className={labelCls}>{t('dbx.structure.name') || 'Name'}</label><input value={name} onChange={(e) => setName(e.target.value)} placeholder={auto} className={`${inputCls} font-mono`} /></div>
        <div>
          <label className={labelCls}>{t('dbx.index.columnsHint') || 'Columns (in the order clicked)'}</label>
          <div className="flex flex-wrap gap-1.5">
            {info.columns.map((c) => {
              const k = cols.indexOf(c.name);
              return (
                <button key={c.name} type="button" onClick={() => setCols(k >= 0 ? cols.filter((x) => x !== c.name) : [...cols, c.name])}
                  className={`rounded-full border px-2 py-0.5 font-mono text-[12px] ${k >= 0 ? 'border-accent/40 bg-accent/15 text-accent' : 'border-border text-text-secondary hover:text-text-primary'}`}>
                  {k >= 0 && <span className="mr-1 text-[10px]">{k + 1}</span>}{c.name}
                </button>
              );
            })}
          </div>
        </div>
        <label className="inline-flex items-center gap-2 text-sm text-text-secondary"><input type="checkbox" checked={unique} onChange={(e) => setUnique(e.target.checked)} className="accent-[rgb(var(--c-accent))]" />UNIQUE</label>
      </div>
    </Modal>
  );
}

/** New foreign key: columns → referenced table columns, ON DELETE / ON UPDATE. */
export function ForeignKeyModal({ instanceId, dbId, info, tables, onClose, onRequest }: {
  instanceId: number; dbId: number; info: DbxTableInfo; tables: DbxTable[]; onClose: () => void; onRequest: (r: DbxDdlRequest, title: string) => void;
}) {
  const { t } = useTranslation();
  const [refTable, setRefTable] = useState('');
  const [refInfo, setRefInfo] = useState<DbxTableInfo | null>(null);
  const [pairs, setPairs] = useState<Array<{ col: string; ref: string }>>([{ col: info.columns[0]?.name ?? '', ref: '' }]);
  const [onDelete, setOnDelete] = useState<DbxFkAction>('RESTRICT');
  const [onUpdate, setOnUpdate] = useState<DbxFkAction>('CASCADE');
  const [name, setName] = useState('');
  useEffect(() => {
    setRefInfo(null);
    if (!refTable) return;
    dbExplorerApi.table(instanceId, dbId, refTable).then((r) => {
      setRefInfo(r);
      const pk = r.primaryKey;
      if (pk.length) setPairs((p) => pk.map((k, i) => ({ col: p[i]?.col ?? info.columns[0]?.name ?? '', ref: k })));
    }).catch((err) => toast.error(explorerError(err)));
  }, [instanceId, dbId, refTable, info.columns]);
  const auto = `fk_${info.table.name}_${refInfo?.table.name ?? 'ref'}`.slice(0, 60);
  const sel = `${inputCls} font-mono`;
  return (
    <Modal open onClose={onClose} size="lg" title={t('dbx.fk.addTitle') || 'New foreign key'}
      footer={<div className="flex justify-end gap-2"><Button variant="secondary" onClick={onClose}>{t('common.cancel') || 'Cancel'}</Button>
        <Button disabled={!refInfo || pairs.some((p) => !p.col || !p.ref)} onClick={() => onRequest({
          op: 'addForeignKey', table: info.table.id, name: name.trim() || auto, columns: pairs.map((p) => p.col), refTable, refColumns: pairs.map((p) => p.ref), onDelete, onUpdate,
        }, t('dbx.fk.addTitle') || 'New foreign key')}>{t('dbx.ddl.preview') || 'Preview the DDL'}</Button></div>}>
      <div className="space-y-3">
        <div className="grid gap-3 sm:grid-cols-2">
          <div><label className={labelCls}>{t('dbx.structure.name') || 'Name'}</label><input value={name} onChange={(e) => setName(e.target.value)} placeholder={auto} className={sel} /></div>
          <div>
            <label className={labelCls}>{t('dbx.fk.refTable') || 'Referenced table'}</label>
            <select value={refTable} onChange={(e) => setRefTable(e.target.value)} className={sel}>
              <option value="">—</option>
              {tables.filter((x) => x.kind === 'table').map((x) => <option key={x.id} value={x.id}>{x.id}</option>)}
            </select>
          </div>
        </div>
        {pairs.map((p, i) => (
          <div key={i} className="flex items-center gap-2">
            <select value={p.col} onChange={(e) => setPairs(pairs.map((x, k) => (k === i ? { ...x, col: e.target.value } : x)))} className={sel}>
              {info.columns.map((c) => <option key={c.name} value={c.name}>{c.name}</option>)}
            </select>
            <span className="text-text-muted">→</span>
            <select value={p.ref} onChange={(e) => setPairs(pairs.map((x, k) => (k === i ? { ...x, ref: e.target.value } : x)))} className={sel} disabled={!refInfo}>
              <option value="">—</option>
              {refInfo?.columns.map((c) => <option key={c.name} value={c.name}>{c.name}</option>)}
            </select>
            {pairs.length > 1 && <IconButton size="sm" label={t('common.delete') || 'Delete'} icon={<Trash2 className="h-4 w-4" />} onClick={() => setPairs(pairs.filter((_, k) => k !== i))} />}
          </div>
        ))}
        <Button size="sm" variant="ghost" onClick={() => setPairs([...pairs, { col: info.columns[0]?.name ?? '', ref: '' }])}><Plus className="mr-1 h-3.5 w-3.5" />{t('dbx.fk.addPair') || 'Another column'}</Button>
        <div className="grid gap-3 sm:grid-cols-2">
          {([['ON DELETE', onDelete, setOnDelete], ['ON UPDATE', onUpdate, setOnUpdate]] as const).map(([label, v, set]) => (
            <div key={label}>
              <label className={labelCls}>{label}</label>
              <select value={v} onChange={(e) => set(e.target.value as DbxFkAction)} className={sel}>{DBX_FK_ACTIONS.map((a) => <option key={a} value={a}>{a}</option>)}</select>
            </div>
          ))}
        </div>
      </div>
    </Modal>
  );
}
