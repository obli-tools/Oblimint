<?php
// ─────────────────────────────────────────────────────────────────────────────
// Oblimint — generated part of the SnappyMail data folder, rewritten at every
// start from the panel-provided environment (docs/P4-PLAN.md §9.7):
//   _data_/_default_/domains/default.json    every mail domain → the engine
//                                             endpoints on the mail network
//   _data_/_default_/configs/application.ini  admin panel off, plugin on, logs off
//                                             (checked on every request by
//                                             /opt/snappymail/include.php)
// No plugin code goes into the data folder (ARCHITECTURE §1): SnappyMail
// loads its plugins from the root-owned /usr/local/lib/oblimint/
// snappymail-plugin/ (APP_PLUGINS_PATH, include.php); a copy left in
// _data_/_default_/plugins/oblimint-sso by an earlier image is removed.
//   php oblimint-snappymail-setup.php /var/lib/snappymail
// Inside the private mail network the engine presents the certificate of its
// public name: no peer verification there (plain IMAP when the engine says so).
// ─────────────────────────────────────────────────────────────────────────────

declare(strict_types=1);

function fail(string $msg): void
{
    fwrite(STDERR, "oblimint-snappymail-setup: {$msg}\n");
    exit(1);
}

/** SnappyMail domain "type": 0 = none, 1 = implicit TLS, 2 = STARTTLS. */
function endpoint(string $prefix): ?array
{
    $host = (string) getenv("OBLIMINT_{$prefix}_HOST");
    $port = (string) getenv("OBLIMINT_{$prefix}_PORT");
    $tls = (string) getenv("OBLIMINT_{$prefix}_TLS");
    if ($host === '') {
        return null;
    }
    if (!preg_match('/^[A-Za-z0-9.-]{1,253}$/', $host) || !ctype_digit($port) || (int) $port < 1 || (int) $port > 65535) {
        fail("invalid {$prefix} endpoint");
    }
    return ['host' => $host, 'port' => (int) $port, 'type' => $tls === 'tls' ? 1 : ($tls === 'starttls' ? 2 : 0)];
}

/** tmp + rename in the same directory; never writes through a symlink. */
function writeAtomic(string $path, string $content): void
{
    $dir = dirname($path);
    if (!is_dir($dir) && !mkdir($dir, 0750, true) && !is_dir($dir)) {
        fail("cannot create {$dir}");
    }
    if (is_link($path) || is_link($dir)) {
        fail("{$path}: symlink refused");
    }
    $tmp = $path . '.tmp-' . bin2hex(random_bytes(4));
    if (file_put_contents($tmp, $content) === false || !chmod($tmp, 0640) || !rename($tmp, $path)) {
        @unlink($tmp);
        fail("cannot write {$path}");
    }
}

$data = rtrim($argv[1] ?? '', '/');
if ($data === '' || !is_dir($data) || is_link($data)) {
    fail('usage: oblimint-snappymail-setup.php <data folder>');
}
$base = "{$data}/_data_/_default_";

$ssl = [
    'verify_peer' => false, 'verify_peer_name' => false, 'allow_self_signed' => true, 'SNI_enabled' => true,
    'disable_compression' => true, 'security_level' => 1,
];
$sasl = ['PLAIN', 'LOGIN'];
$imap = endpoint('IMAP');
if ($imap === null) {
    fail('OBLIMINT_IMAP_HOST is not set');
}
$smtp = endpoint('SMTP');
$sieve = endpoint('SIEVE');

$domain = [
    'IMAP' => $imap + [
        'timeout' => 300, 'shortLogin' => false, 'lowerLogin' => true, 'sasl' => $sasl, 'ssl' => $ssl,
        'disabled_capabilities' => ['METADATA', 'OBJECTID', 'PREVIEW', 'STATUS=SIZE'], 'use_expunge_all_on_delete' => false,
        'fast_simple_search' => true, 'force_select' => false, 'message_all_headers' => false, 'message_list_limit' => 10000,
        'search_filter' => '',
    ],
    'SMTP' => ($smtp ?? ['host' => $imap['host'], 'port' => 587, 'type' => 2]) + [
        'timeout' => 60, 'shortLogin' => false, 'lowerLogin' => true, 'sasl' => $sasl, 'ssl' => $ssl,
        'useAuth' => true, 'setSender' => false, 'usePhpMail' => false,
    ],
    'Sieve' => ($sieve ?? ['host' => $imap['host'], 'port' => 4190, 'type' => 0]) + [
        'timeout' => 10, 'shortLogin' => false, 'lowerLogin' => true, 'sasl' => $sasl, 'ssl' => $ssl, 'enabled' => $sieve !== null,
    ],
    'whiteList' => '',
];
writeAtomic("{$base}/domains/default.json", json_encode($domain, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");

$max = max(1, (int) (getenv('OBLIMINT_MAX_MESSAGE_MB') ?: 50));
$ini = implode("\n", [
    '; Generated by Oblimint at every start (images/webmail-snappymail).',
    '[webmail]',
    'title = "Webmail"',
    'language = "fr"',
    "attachment_size_limit = {$max}",
    '',
    '[security]',
    'allow_admin_panel = Off',
    '',
    '[login]',
    'sign_me_auto = "DefaultOff"',
    '',
    '[plugins]',
    'enable = On',
    'enabled_list = "oblimint-sso"',
    '',
    '[logs]',
    'enable = Off',
    '',
]);
writeAtomic("{$base}/configs/application.ini", $ini);

// Earlier images copied the plugin into the data folder: never loaded any
// more (APP_PLUGINS_PATH), removed so no PHP is left in the writable tree.
$stale = "{$base}/plugins/oblimint-sso";
if (is_link($stale)) {
    @unlink($stale) || fail("cannot remove {$stale}");
} elseif (is_dir($stale)) {
    foreach (scandir($stale) ?: [] as $entry) {
        if ($entry !== "." && $entry !== ".." && (is_link("{$stale}/{$entry}") || is_file("{$stale}/{$entry}"))) {
            @unlink("{$stale}/{$entry}") || fail("cannot remove {$stale}/{$entry}");
        }
    }
    // Not loaded either way: a left-over sub-directory only gets a warning.
    @rmdir($stale) || fwrite(STDERR, "oblimint-snappymail-setup: {$stale} not empty, left in place (never loaded)\n");
}
