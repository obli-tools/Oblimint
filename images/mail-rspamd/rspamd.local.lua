--[[
images/mail-rspamd — Oblimint limits (module engine-postfix, MA9):

  * hourly send limit per authenticated mailbox (SASL user): fixed one-hour
    window counted in Redis, "soft reject" (4xx, the client retries later)
    above the limit; fails CLOSED (soft reject) when the counter cannot be
    incremented (Redis unreachable or out of memory). Limits: /etc/rspamd/local.d/oblimint_sendlimits.map
    ("address messages-per-hour"), generated by the panel;
  * the same hourly limits for mail the engine re-sends without SASL (MA9):
    forwarding / alias / catch-all to an external target, counted per local
    recipient (/etc/rspamd/local.d/oblimint_fwdlimits.map, a mailbox shares
    its SASL counter), and Sieve redirect (loopback submission, envelope sender =
    the mailbox);
  * per-domain maximum message size (domain → bytes), for the sender's domain
    of an authenticated message and for every recipient domain:
    /etc/rspamd/local.d/oblimint_sizelimits.map. Postfix's message_size_limit
    already enforces the platform ceiling.

  * header From of an authenticated message (MA3 / MA5): exactly one
    address, equal to the envelope sender (which Postfix checks against the
    SASL login, the null sender being refused on submission); anything else
    is rejected, so a mailbox can neither get another domain signed nor
    deliver a header-spoofed message to a local mailbox (authenticated mail
    skips SPF / DMARC).

The maps are generated by the panel (postfixDovecot/confRspamd.ts) and are
reloaded by Rspamd when they change. Never logs message content.
]]

local rspamd_logger = require "rspamd_logger"
local rspamd_util = require "rspamd_util"
local lua_redis = require "lua_redis"
local lua_util = require "lua_util"

local N = 'oblimint'
local MAPDIR = '/etc/rspamd/local.d/'
local WINDOW = 3600

local send_limits = rspamd_config:add_map({
  type = 'map',
  url = MAPDIR .. 'oblimint_sendlimits.map',
  description = 'Oblimint: messages per hour per authenticated mailbox',
})
local fwd_limits = rspamd_config:add_map({
  type = 'map',
  url = MAPDIR .. 'oblimint_fwdlimits.map',
  description = 'Oblimint: messages per hour re-sent outside by forwarding / aliases / catch-all',
})
local size_limits = rspamd_config:add_map({
  type = 'map',
  url = MAPDIR .. 'oblimint_sizelimits.map',
  description = 'Oblimint: maximum message size per domain (bytes)',
})

local redis_params = lua_redis.parse_redis_server(N)
local incr_script_id = nil
if redis_params then
  incr_script_id = lua_redis.add_redis_script([[
local n = redis.call('INCR', KEYS[1])
if n == 1 then redis.call('EXPIRE', KEYS[1], tonumber(ARGV[1])) end
return n
]], redis_params)
else
  rspamd_logger.errx(rspamd_config, 'oblimint: no Redis configured, hourly send limits are NOT enforced')
end

local function domain_of(addr)
  if type(addr) ~= 'string' then return nil end
  local d = addr:match('@([^@]+)$')
  return d and d:lower() or nil
end

-- true when the message was refused for its size
local function check_size(task)
  local size = task:get_size()
  if not size or size == 0 then return false end
  local seen = {}
  local function over(domain)
    if not domain or seen[domain] then return false end
    seen[domain] = true
    local limit = tonumber(size_limits:get_key(domain))
    return limit ~= nil and size > limit
  end
  if over(domain_of(task:get_user())) then
    task:set_pre_result('reject', 'Message too large for the sender domain', N)
    return true
  end
  for _, rcpt in ipairs(task:get_recipients('smtp') or {}) do
    if over(rcpt.domain and rcpt.domain:lower()) then
      task:set_pre_result('reject', 'Message too large for the recipient domain', N)
      return true
    end
  end
  return false
end

-- one hourly counter (shared by every path of the same address)
local function count(task, subject, limit)
  local key = string.format('oblimint:rl:%s:%d', subject, math.floor(rspamd_util.get_time() / WINDOW))
  lua_redis.exec_redis_script(incr_script_id, { task = task, is_write = true, key = key },
    function(err, data)
      if err then
        -- Fail closed (MA9): a counter that cannot be written (Redis down,
        -- OOM) must never lift the limit; the client retries later.
        rspamd_logger.errx(task, 'oblimint: send limit counter unavailable for %s: %s', subject, err)
        task:set_pre_result('soft reject', 'Sending limit cannot be checked, try again later', N)
        return
      end
      if (tonumber(data) or 0) > limit then
        rspamd_logger.infox(task, 'oblimint: hourly send limit (%s) reached by %s', limit, subject)
        task:set_pre_result('soft reject', 'Hourly sending limit reached, try again later', N)
      end
    end, { key }, { tostring(2 * WINDOW) })
end

-- mail generated inside oblimint-mail (Sieve redirect / vacation of Dovecot,
-- handed to the loopback Sieve submission smtpd; non_smtpd_milters for the
-- rest of the local mail):
-- Postfix reports the client as 127.0.0.1 / ::1
local function is_pickup(task)
  local ip = task:get_from_ip()
  if not ip or not ip:is_valid() then return true end
  local s = tostring(ip)
  return s == '127.0.0.1' or s == '::1'
end

local function check_rate(task)
  if not incr_script_id then return end
  local user = task:get_user()
  if type(user) == 'string' then
    user = user:lower()
    local limit = tonumber(send_limits:get_key(user))
    if limit then count(task, user, limit) end
    return
  end
  -- MA9: mail the engine sends on behalf of a mailbox without SASL.
  -- Sieve redirect leaves with the mailbox as envelope sender
  -- (sieve_redirect_envelope_from = recipient): its SASL counter.
  if is_pickup(task) then
    local env = task:get_from('smtp')
    local from = env and env[1] and env[1].addr
    if type(from) == 'string' and from ~= '' then
      from = from:lower()
      local limit = tonumber(send_limits:get_key(from))
      if limit then count(task, from, limit) end
    end
    return
  end
  -- Forwarding / alias / catch-all to an external target: counted per local
  -- recipient ('-' = existing address of a catch-all domain, not counted).
  local seen = {}
  for _, rcpt in ipairs(task:get_recipients('smtp') or {}) do
    local addr = type(rcpt.addr) == 'string' and rcpt.addr:lower() or nil
    if addr and not seen[addr] then
      seen[addr] = true
      local subject, v = addr, fwd_limits:get_key(addr)
      if v == nil then
        local d = domain_of(addr)
        if d then subject, v = '@' .. d, fwd_limits:get_key('@' .. d) end
      end
      local limit = tonumber(v)
      if limit and not seen[subject .. '#'] then
        seen[subject .. '#'] = true
        count(task, subject, limit)
      end
    end
  end
end

-- true when the authenticated message was refused for its header From
local function check_hdrfrom(task)
  if type(task:get_user()) ~= 'string' then return false end
  local env = task:get_from('smtp')
  local hdr = task:get_from('mime')
  local env_addr = env and env[1] and env[1].addr
  local ok = type(env_addr) == 'string' and env_addr ~= '' and hdr and #hdr == 1
    and type(hdr[1].addr) == 'string' and hdr[1].addr:lower() == env_addr:lower()
  if not ok then
    rspamd_logger.infox(task, 'oblimint: header From does not match the envelope sender of %s', task:get_user())
    task:set_pre_result('reject', 'The From header must be your sender address', N)
    return true
  end
  return false
end

rspamd_config:register_symbol({
  name = 'OBLIMINT_LIMITS',
  type = 'prefilter',
  priority = (lua_util.symbols_priorities or {}).high,
  callback = function(task)
    if check_hdrfrom(task) then return end
    if check_size(task) then return end
    check_rate(task)
  end,
})
