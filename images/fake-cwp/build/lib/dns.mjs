// ─────────────────────────────────────────────────────────────────────────────
// fake-cwp — BIND 9.11 layout of CWP (CWP-MAP §9): /etc/named.conf with the
// zones declared INLINE at the end, /var/named/<zone>.db in CWP free format
// (docs/cwp/zone-sample.anon.db), one zone rewritten by BIND (canonical), one
// DYNAMIC zone (allow-update key "cwp-updater", key file in /etc/named/keys),
// an orphan .db and a .restore copy. The journal (.jnl) of the dynamic zone is
// produced at the first container start (bin/fake-cwp-entrypoint, nsupdate).
// ─────────────────────────────────────────────────────────────────────────────

export const ZONE_DIR = '/var/named';
export const SERIAL = 2025090843;

function abs(name, zone) {
  return name === '@' ? `${zone}.` : `${name}.${zone}.`;
}

/** Splits a long TXT payload in ≤ 255-byte quoted strings (BIND limit per string). */
export function txtStrings(value, size = 250) {
  const parts = [];
  for (let i = 0; i < value.length; i += size) parts.push(`"${value.slice(i, i + size)}"`);
  return parts.join(' ');
}

export function dkimTxtValue(publicB64) {
  return `v=DKIM1; k=rsa; p=${publicB64}`;
}

/** Records of a zone: [name, ttl, type, content] (name relative, '@' = apex), SOA / NS excluded. */
export function zoneRecords(ds, zone, dkimPublic) {
  const S = ds.SERVER;
  const ip = S.publicIp;
  const recs = [];
  if (zone.standard) {
    const z = zone.name;
    recs.push(
      ['@', null, 'A', ip],
      [`localhost.${z}.`, null, 'A', '127.0.0.1'],
      ['@', null, 'MX', `0 ${z}.`],
      ['mail', 14400, 'CNAME', `${z}.`],
      ['smtp', 14400, 'CNAME', `${z}.`],
      ['pop', 14400, 'CNAME', `${z}.`],
      ['pop3', 14400, 'CNAME', `${z}.`],
      ['imap', 14400, 'CNAME', `${z}.`],
      ['webmail', 14400, 'A', ip],
      ['cpanel', 14400, 'A', ip],
      ['cwp', 14400, 'A', ip],
      ['www', 14400, 'CNAME', `${z}.`],
      ['ftp', 14400, 'CNAME', `${z}.`],
      ['_dmarc', 14400, 'TXT', '"v=DMARC1; p=none"'],
      ['@', 14400, 'TXT', `"v=spf1 +a +mx +ip4:${ip} ~all"`],
    );
    if (dkimPublic) recs.push(['default._domainkey', 14400, 'TXT', `( ${txtStrings(dkimTxtValue(dkimPublic))} )`]);
  }
  for (const r of zone.records ?? []) recs.push(r);
  for (const r of zone.extra ?? []) recs.push(r);
  return recs;
}

function cwpZoneFile(ds, zone, recs) {
  const [ns1, ns2] = ds.SERVER.nameservers.map((n) => n.name);
  const lines = [
    '; Generated by CWP',
    `; Zone file for ${zone.name}`,
    '$TTL 14400',
    `@    86400        IN      SOA     ${ns1}. postmaster.${zone.name}. (`,
    `				${SERIAL} ; serial, todays date+todays`,
    '				3600            ; refresh, seconds',
    '				7200            ; retry, seconds',
    '				1209600         ; expire, seconds',
    '				86400 )         ; minimum, seconds',
    `@	86400	IN	NS		${ns1}.`,
    `@	86400	IN	NS		${ns2}.`,
  ];
  for (const [name, ttl, type, content] of recs) {
    if (type === 'TXT' && (name === '@' || name === '_dmarc')) lines.push(`${name}\t${ttl}\tIN\t${type}\t${content}`);
    else if (ttl === null) lines.push(`${name} IN ${type} ${content}`);
    else lines.push(`${name} ${ttl} IN ${type} ${content}`);
  }
  return `${lines.join('\n')}\n`;
}

/** Master file as BIND dumps it ($ORIGIN blocks, owner inheritance, explicit TTLs): a zone "rewritten by BIND". */
function canonicalZoneFile(ds, zone, recs) {
  const [ns1, ns2] = ds.SERVER.nameservers.map((n) => n.name);
  const z = zone.name;
  const apex = recs.filter(([n]) => n === '@');
  const others = recs
    .filter(([n]) => n !== '@')
    .map(([n, t, ty, c]) => [n.endsWith('.') ? n.slice(0, -(z.length + 2)) : n, t, ty, c])
    .sort((a, b) => a[0].localeCompare(b[0]));
  const lines = [
    '$ORIGIN .',
    '$TTL 14400	; 4 hours',
    `${z}		IN SOA	${ns1}. postmaster.${z}. (`,
    `				${SERIAL} ; serial`,
    '				3600       ; refresh (1 hour)',
    '				7200       ; retry (2 hours)',
    '				1209600    ; expire (2 weeks)',
    '				86400      ; minimum (1 day)',
    '				)',
    `			86400	NS	${ns1}.`,
    `			86400	NS	${ns2}.`,
  ];
  for (const [, t, ty, c] of apex) lines.push(`			${t ?? 14400}	${ty}	${c}`);
  lines.push(`$ORIGIN ${z}.`);
  let prev = null;
  for (const [n, t, ty, c] of others) {
    const owner = n === prev ? '\t\t\t' : `${n}${n.length < 8 ? '\t\t\t' : n.length < 16 ? '\t\t' : '\t'}`;
    lines.push(`${owner}${t ?? 14400}\t${ty}\t${c}`);
    prev = n;
  }
  return `${lines.join('\n')}\n`;
}

export function renderDns(ds, plan, crypto, dkimPublicByDomain) {
  const S = ds.SERVER;
  const named = { owner: 'root', group: 'named' };
  plan.dir(ZONE_DIR, { ...named, mode: 0o770 });
  const zoneFiles = {};
  for (const zone of ds.ZONES) {
    const recs = zoneRecords(ds, zone, dkimPublicByDomain[zone.name] ?? null);
    const content = zone.format === 'canonical' ? canonicalZoneFile(ds, zone, recs) : cwpZoneFile(ds, zone, recs);
    const file = `${ZONE_DIR}/${zone.name}.db`;
    plan.file(file, content, { ...named, mode: 0o640 });
    zoneFiles[zone.name] = file;
  }
  for (const extra of ds.ZONE_FILES_EXTRA) {
    const zone = ds.ZONES.find((z) => z.name === extra.zone) ?? { name: extra.zone, standard: true, extra: [] };
    const recs = zoneRecords(ds, zone, null);
    plan.file(`${ZONE_DIR}/${extra.file}`, cwpZoneFile(ds, zone, recs), { ...named, mode: 0o640 });
  }

  // TSIG key of the dynamic zone (secret generated at build; the panel never reads /etc/named/keys).
  plan.dir('/etc/named', { ...named, mode: 0o750 });
  plan.dir('/etc/named/keys', { ...named, mode: 0o750 });
  plan.file(`/etc/named/keys/${S.dnsUpdateKey}.key`,
    `key "${S.dnsUpdateKey}" {\n\talgorithm hmac-sha256;\n\tsecret "${crypto.tsigSecret()}";\n};\n`, { ...named, mode: 0o640 });

  // Dynamic update replayed ONCE by the entrypoint at the first start (named running): creates the .jnl and
  // leaves the .db file stale — the records exist only through the journal (named-checkzone -j / AXFR).
  const dyn = ds.ZONES.filter((z) => z.dynamic);
  if (dyn.length !== 1) throw new Error('exactly one dynamic zone expected');
  const dz = dyn[0];
  plan.file('/opt/fake-cwp/generated/nsupdate.txt', [
    'server 127.0.0.1',
    `zone ${dz.name}`,
    ...dz.dynamicRecords.map(([n, ttl, type, content]) => `update add ${n}.${dz.name}. ${ttl} IN ${type} ${content}`),
    'send',
    '',
  ].join('\n'), { mode: 0o600 });

  const zonesConf = ds.ZONES.map((z) => {
    const update = z.dynamic ? ` allow-update { key "${S.dnsUpdateKey}"; };` : '';
    return `zone "${z.name}" {type master; file "${zoneFiles[z.name]}";${update}};`;
  });
  plan.file('/etc/named.conf', `//
// named.conf — CentOS Web Panel layout (fake-cwp, TEST ONLY).
// Zones are declared inline at the end of the file, as CWP does.
//
options {
	listen-on port 53 { 127.0.0.1; };
	listen-on-v6 port 53 { ::1; };
	directory	"/var/named";
	dump-file	"/var/named/data/cache_dump.db";
	statistics-file "/var/named/data/named_stats.txt";
	memstatistics-file "/var/named/data/named_mem_stats.txt";
	recursing-file	"/var/named/data/named.recursing";
	secroots-file	"/var/named/data/named.secroots";
	allow-query	{ any; };
	allow-transfer	{ 127.0.0.1; };
	recursion no;
	dnssec-validation no;
	managed-keys-directory "/var/named/dynamic";
	pid-file "/run/named/named.pid";
	session-keyfile "/run/named/session.key";
};

logging {
	channel default_debug {
		file "data/named.run";
		severity dynamic;
	};
};

include "/etc/named/keys/${S.dnsUpdateKey}.key";

${zonesConf.join('\n')}
`, { ...named, mode: 0o640 });
  return zoneFiles;
}
