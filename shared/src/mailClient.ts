// =============================================================================
// « Se connecter à Mint » — desktop mail clients (MailForge) and device
// passwords of a mailbox. Lot 1 (L1a, L1b, L1c):
//
//  - public discovery document (O2): GET /.well-known/oblimint/mail-client on
//    autoconfig.<domain> (the domain part) and on the panel hosts. It never
//    names the mail engine nor a capability that would betray it (owner's
//    decision P6): those only travel in authenticated answers (`servers`);
//  - device passwords (O4a): mail_app_passwords rows of purpose 'device',
//    one per (device, mailbox), 32 random bytes generated by the server,
//    shown once, hashed; login = the mailbox address. Lot 1 creates them by
//    hand from the mailbox page (client 'manual'); MailForge (client
//    'mailforge', OAuth) comes with lot 2;
//  - device API (C7 / C8): GET / DELETE /api/v1/mail/device/self with
//    `Authorization: Basic base64("omd_<id>:<password>")` — status of the
//    credential (a revoked one answers 200 status "revoked", never 401).
// =============================================================================

/** Client id of MailForge (OAuth public client, lot 2). */
export const MAIL_CLIENT_ID = 'mailforge';
/** The only scope of the MailForge client (lot 2). */
export const MAIL_CLIENT_SCOPE = 'mail.client';
/** Path of the discovery document (autoconfig.<domain> and the panel hosts). */
export const MAIL_CLIENT_DISCOVERY_PATH = '/.well-known/oblimint/mail-client';

/** Public id of a device password: 'omd_' + 16 base32 characters (lower case). */
export const MAIL_DEVICE_ID_PREFIX = 'omd_';
export const MAIL_DEVICE_PUBLIC_ID_RE = /^omd_[a-z2-7]{16}$/;
/**
 * Live device passwords per mailbox, MailForge and manual together: the
 * postfix-dovecot slot count of the device reserve (one passwd-file per slot
 * and service). The platform setting mail.maxDevicesPerMailbox may only lower it.
 */
export const MAIL_DEVICE_SLOTS = 10;

export type MailDeviceClient = 'mailforge' | 'manual';
/** Right of the creator: mailforge ⇒ assigned | owner (lot 2); manual ⇒ assigned | manage. */
export type MailDeviceBasis = 'assigned' | 'owner' | 'manage';
export type MailDeviceProtocol = 'imap' | 'pop3' | 'smtp';
export type MailDeviceRevokedReason = 'device' | 'user' | 'manager' | 'basis' | 'password' | 'containment' | 'expired' | 'replaced';
export const MAIL_DEVICE_REVOKED_REASONS: readonly MailDeviceRevokedReason[] = [
  'device', 'user', 'manager', 'basis', 'password', 'containment', 'expired', 'replaced',
];

/** Protocol sets a manual app password may get. */
export type MailDeviceProtocolSet = 'imapSmtp' | 'all';
export const MAIL_DEVICE_PROTOCOL_SETS: Readonly<Record<MailDeviceProtocolSet, readonly MailDeviceProtocol[]>> = {
  imapSmtp: ['imap', 'smtp'],
  all: ['imap', 'pop3', 'smtp'],
};
/** Lifetimes offered for a manual app password (days), capped by mail.manualAppPasswordMaxDays. */
export const MANUAL_APP_PASSWORD_DAYS: readonly number[] = [90, 365, 1095];
export const MANUAL_APP_PASSWORD_DEFAULT_DAYS = 365;

export type MailDeviceStatus = 'active' | 'revoked' | 'expired' | 'suspended';

/** One device password as the panel lists it (never the secret, never a hash). */
export interface MailDevice {
  /** Public id (omd_…). */
  id: string;
  mailboxId: number;
  label: string;
  client: MailDeviceClient;
  basis: MailDeviceBasis;
  protocols: MailDeviceProtocol[];
  /** User the device was created for (the creator for a manual one), null = deleted user. */
  createdFor: { id: number; name: string } | null;
  createdAt: string;
  expiresAt: string;
  /** Last call of the device API (MailForge check-in), null = never. */
  lastSeenAt: string | null;
  lastSeenIp: string | null;
  revokedAt: string | null;
  revokedReason: MailDeviceRevokedReason | null;
}

export interface MailDeviceList {
  /** Live device passwords (unrevoked, unexpired), newest first. */
  items: MailDevice[];
  /** Ceiling per mailbox (settings mail.maxDevicesPerMailbox ≤ MAIL_DEVICE_SLOTS). */
  max: number;
  /** Longest lifetime of a manual app password (days, settings). */
  manualMaxDays: number;
  /** The engine cannot refuse POP3 to a device password (Stalwart 0.12.4): IMAP+SMTP still opens POP3. */
  pop3AlwaysOpen: boolean;
}

/** POST /api/mail/mailboxes/:id/devices — manual app password (O4a). */
export interface MailDeviceCreate {
  label: string;
  /** One of MANUAL_APP_PASSWORD_DAYS, ≤ mail.manualAppPasswordMaxDays. */
  days: number;
  protocols: MailDeviceProtocolSet;
}

/** The secret is returned ONCE (never stored in clear, never logged). */
export interface MailDeviceCreated {
  device: MailDevice;
  /** Login on IMAP / SMTP: the mailbox address. */
  username: string;
  password: string;
}

/** POST /api/mail/mailboxes/:id/devices/revoke — one (id) or all (all: true) live device passwords of the mailbox. */
export interface MailDeviceRevoke {
  id?: string;
  all?: boolean;
}

// ── discovery (O2) ───────────────────────────────────────────────────────────

export interface MailClientServerEndpoint {
  host: string;
  port: number;
  security: 'tls' | 'starttls';
}

/** Public document (C1). No engine, no engine-only capability (P6). */
export interface MailClientDiscovery {
  version: 1;
  product: 'oblimint';
  /** The mail domain (autoconfig.<domain>); absent on the panel hosts. */
  domain?: string;
  /** Origins that may issue an authorization (panel, client space). */
  issuers: string[];
  panelUrl: string | null;
  clientSpaceUrl: string | null;
  oauth: {
    clientId: string;
    scope: string;
    /** false while the MailForge sign-in is not offered (lot 2 not there yet, or settings mail.desktopClients off). */
    enabled: boolean;
    /** issuer → its endpoints (same origin as the issuer); empty while enabled is false. */
    endpoints: Record<string, { authorization: string; token: string }>;
  };
  mail: {
    username: 'address';
    authMechanisms: ['PLAIN'];
    imap: MailClientServerEndpoint[];
    smtp: MailClientServerEndpoint[];
    pop3: MailClientServerEndpoint[];
    tlsNames: string[];
    capabilities: {
      devicePasswords: boolean;
      deviceApi: boolean;
      manualAppPasswords: boolean;
      panelRules: boolean;
      idle: boolean;
      jmap: boolean;
      caldav: boolean;
      carddav: boolean;
    };
    limits: { maxMessageBytes: number };
    authBan: { threshold: number; windowMinutes: number; durationMinutes: number; revokedAllowance: boolean };
  };
  /** Webmail of the domain (autoconfig.<domain> only), null = none. */
  webmailUrl?: string | null;
}

/** Engine-dependent details, in AUTHENTICATED answers only (device API, lot 2 client API). */
export interface MailClientServers {
  engine: 'postfix-dovecot' | 'stalwart';
  imap: MailClientServerEndpoint[];
  smtp: MailClientServerEndpoint[];
  pop3: MailClientServerEndpoint[];
  managesieve: MailClientServerEndpoint | null;
  serverFullTextSearch: boolean;
  /** Simultaneous IMAP connections per (user, IP), null = no known limit. */
  imapConnectionsPerUserIp: number | null;
  authMechanisms: string[];
}

// ── device API (C7 / C8) ─────────────────────────────────────────────────────

/** GET /api/v1/mail/device/self. A revoked / expired credential still gets 200 with its status. */
export interface MailDeviceSelf {
  id: string;
  mailboxId: number;
  address: string;
  label: string;
  status: MailDeviceStatus;
  revokedReason: MailDeviceRevokedReason | null;
  /** A sync that started after the credential was issued applied the mailbox's domain. */
  engineReady: boolean;
  expiresAt: string;
  protocols: MailDeviceProtocol[];
  /** null when the credential is not active. */
  servers: MailClientServers | null;
}
