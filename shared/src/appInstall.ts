// =============================================================================
// Oblimint — immutable application installer (V1: WordPress only).
//
// Unlike the catalogue's Docker application (mutable code on a writable
// volume), the code ends up in a release: read-only, analysed, with a rollback.
// One tracked operation, with visible steps:
//   site → database (instance, database, user) → variables → download (archive
//   pre-downloaded by the panel, checksums verified) → extract → config
//   (a wp-config.php reading the environment) → verify (per-file checksums) →
//   install (wp core install) → [preview] → publish (release 1).
// The admin password is generated by the panel, returned ONCE by the starting
// call, never logged, audited nor passed as a command argument.
// =============================================================================

import type { PublishMode, SiteBaseId } from './hosting';

export const APP_INSTALL_APPS = ['wordpress'] as const;
export type AppInstallApp = typeof APP_INSTALL_APPS[number];

export const APP_INSTALL_STEPS = ['site', 'database', 'variables', 'download', 'extract', 'config', 'verify', 'install', 'preview', 'publish'] as const;
export type AppInstallStepKey = typeof APP_INSTALL_STEPS[number];
export type AppInstallStepStatus = 'pending' | 'running' | 'done' | 'failed' | 'skipped';

export interface AppInstallStep {
  key: AppInstallStepKey;
  status: AppInstallStepStatus;
  startedAt: string | null;
  finishedAt: string | null;
}

/**
 * running: the steps are under way; preview_ready: installed, shown in a
 * preview, waits for the decision to publish; awaiting_approval: release 1
 * waits for an approver (site in mode 'approval'); succeeded: release 1 is
 * live; failed: stopped on a step (retry, or cleanup); cleaned: what the
 * operation had created was removed.
 */
export const APP_INSTALL_STATUSES = ['running', 'preview_ready', 'awaiting_approval', 'succeeded', 'failed', 'cleaning', 'cleaned'] as const;
export type AppInstallStatus = typeof APP_INSTALL_STATUSES[number];
export const APP_INSTALL_IN_FLIGHT: readonly AppInstallStatus[] = ['running', 'cleaning'];

/** Letters, digits, dot, dash, underscore; never a leading dash. */
export const APP_INSTALL_ADMIN_USER_RE = /^[A-Za-z0-9_][A-Za-z0-9._-]{0,59}$/;
/** en_US, fr_FR, de_DE_formal, es_419… (the locale of the WordPress build). */
export const APP_INSTALL_LOCALE_RE = /^[a-z]{2,3}(?:_[A-Z0-9]{2,3})?(?:_[a-z0-9]{1,12})?$/;
/** Room asked on the account before starting (the code in the staging and in a release, plus the database). */
export const APP_INSTALL_MIN_FREE_DISK_MB = 300;

export interface AppInstallStartRequest {
  accountId: number;
  app: AppInstallApp;
  name: string;
  slug: string;
  /** PHP base (default: the recommended one of the WordPress profile). */
  base?: SiteBaseId;
  publishMode?: PublishMode;
  publishDebounceSec?: number;
  /** Title of the site (default: name). */
  title?: string;
  adminUser: string;
  adminEmail: string;
  /** Default en_US. */
  locale?: string;
  /** Stop in a preview (staging + disposable copy of the database) before publishing. */
  previewFirst?: boolean;
}

export interface AppInstallLogLine {
  at: string;
  level: 'info' | 'warn' | 'error';
  message: string;
}

export interface AppInstall {
  id: number;
  tenantId: number;
  accountId: number;
  siteId: number | null;
  siteSlug: string;
  siteName: string;
  app: AppInstallApp;
  status: AppInstallStatus;
  steps: AppInstallStep[];
  /** Step the operation stopped on (failed). */
  failedStep: AppInstallStepKey | null;
  errorCode: string | null;
  error: string | null;
  version: string | null;
  locale: string;
  adminUser: string;
  adminEmail: string;
  previewFirst: boolean;
  previewId: number | null;
  releaseId: number | null;
  releaseNumber: number | null;
  /** Database objects the operation uses, and whether it created them (a cleanup removes only those). */
  instanceId: number | null;
  databaseId: number | null;
  databaseName: string | null;
  createdObjects: { instance: boolean; database: boolean; user: boolean };
  log: AppInstallLogLine[];
  createdAt: string;
  updatedAt: string;
  finishedAt: string | null;
}

/** POST /api/app-installs · POST /api/v1/apps/install · MCP install_app. */
export interface AppInstallStartResult {
  install: AppInstall;
  adminUser: string;
  /** Shown once: this answer is the only place it ever appears. */
  adminPassword: string;
}

/** Answer of a retry: adminPassword only when a new one had to be generated (the first one was purged). */
export interface AppInstallRetryResult {
  install: AppInstall;
  adminPassword?: string;
}
