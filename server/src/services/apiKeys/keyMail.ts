// ─────────────────────────────────────────────────────────────────────────────
// Mailboxes through an access key (scope mail.mailboxes, opt-in: never in a
// preset): REST /api/v1/mailboxes…, MCP list_mailboxes, create_mailbox,
// reset_mailbox_password, delete_mailbox. No parallel path: every change goes
// through mailService (plan and tenant limits, suspended account, reserved
// local parts, address taken, purge of a previous owner's data, socket event,
// engine sync, audit) with the key's actor — a client-like actor holding
// mail.manage on the key's account only (SCOPE_CAP), so loadMailDomain /
// loadMailbox refuse anything else; the creator must hold mail.manage himself
// (SCOPE_NEED) or the scope is inactive.
//
// Perimeter: the mail domains of the key's account (never another account or
// tenant: 404, no existence oracle), whatever the key's sites or domains.
// Order of the checks: scope, containment, object, format / password strength /
// suspended account — then the gate (mail.mailbox_password, mail.mailbox_delete:
// a second factor of the key's owner by default for a deletion), so nobody
// confirms something that would be refused anyway.
// Secrets: a password (given or generated) is returned ONCE in the answer
// (REST: Cache-Control no-store); it only enters the gate's fingerprint
// (secretParams), never the pending action, the audit nor a log.
// ─────────────────────────────────────────────────────────────────────────────

/** A mailbox named by the caller: its id, or its full address. */
export type KeyMailboxRef = { id: number } | { address: string };

/** A mail domain named by the caller: its id, or its name. */
export interface KeyMailDomainRef {
  mailDomainId?: number | null;
  domain?: string | null;
}

export interface KeyMailboxCreate extends KeyMailDomainRef {
  localPart: string;
  /** Absent / null: generated by the server and returned once. */
  password?: string | null;
  /** MiB; absent: the platform default capped by the plan; null: unlimited (only when the plan allows it). */
  quotaMb?: number | null;
  displayName?: string | null;
}

export interface KeyMailboxQuery extends KeyMailDomainRef {
  search?: string | null;
  limit?: number;
  offset?: number;
}

export const KEY_MAILBOX_PAGE_MAX = 500;

const notFound = (what: string) => new AppError(404, `${what} not found`, 'notFound');
const normalizeName = (raw: unknown) => String(raw ?? '').trim().toLowerCase().replace(/\.$/, '');

/** The mail domain of the key's account named by id or by name (404 otherwise: another account does not exist). */
async function keyMailDomainId(ctx: ApiKeyContext, ref: KeyMailDomainRef): Promise<number> {
  const q = db('mail_domains').where({ account_id: ctx.accountId, tenant_id: ctx.tenantId });
  if (ref.mailDomainId) q.andWhere({ id: ref.mailDomainId });
  else if (ref.domain) q.andWhere({ name: normalizeName(ref.domain) });
  else throw new AppError(400, 'A mail domain is required (domain or mail_domain_id)', 'validation', { field: 'domain' });
  const row = await q.first('id') as { id: number } | undefined;
  if (!row) throw notFound('Mail domain');
  return Number(row.id);
}

/** A mailbox of the key's account, loaded by the mail service's own check (404 elsewhere, 403 without mail.manage). */
async function keyMailbox(ctx: ApiKeyContext, ref: KeyMailboxRef): Promise<MailboxLoaded> {
  const q = db('mailboxes').where({ account_id: ctx.accountId, tenant_id: ctx.tenantId });
  if ('id' in ref) {
    if (!Number.isInteger(ref.id) || ref.id <= 0) throw notFound('Mailbox');
    q.andWhere({ id: ref.id });
  } else {
    q.andWhere({ address: normalizeName(ref.address) });
  }
  const row = await q.first('id') as { id: number } | undefined;
  if (!row) throw notFound('Mailbox');
  return loadMailbox(ctx.actor, Number(row.id), 'mail.manage');
}

/** A change of the account's mail: the scope, then nothing that opens a way in during a containment. */
async function writable(ctx: ApiKeyContext): Promise<void> {
  requireScope(ctx, 'mail.mailboxes');
  await assertNotContained(ctx.accountId);
}

/** 409 accountSuspended, as the mail service answers a creation: no new credential on an account cut from its mail. */
function assertServed(status: string): void {
  if (!accountServesMail(status)) throw new AppError(409, 'The hosting account is suspended', 'accountSuspended');
}

function assertLocalPart(raw: string): string {
  const lp = String(raw ?? '').trim().toLowerCase();
  if (!lp || lp.length > 64 || !LOCAL_PART_RE.test(lp)) {
    throw new AppError(400, 'Invalid mailbox name: lower-case letters, digits, . _ + - (no leading, trailing or doubled dot), 64 at most', 'invalidAddress', { field: 'localPart' });
  }
  return lp;
}

const mailTarget = (r: { tenant_id: number; account_id: number }) => ({ tenantId: Number(r.tenant_id), accountId: Number(r.account_id), siteId: null });

function passwordGate(mb: MailboxLoaded, password: string | null | undefined): GateSpec {
  // The panel's own gate (routes/mail.routes.ts): the password is a secret, its fingerprint only.
  return {
    action: 'mail.mailbox_password', target: mailTarget(mb), params: { mailbox: mb.address, generated: !password },
    secretParams: password ? { password } : {},
  };
}

function mailboxView(m: Mailbox): ApiV1Mailbox {
  return {
    id: m.id, address: m.address, localPart: m.localPart, domain: m.domain, mailDomainId: m.mailDomainId, displayName: m.displayName,
    quotaMb: m.quotaMb, usedBytes: m.usedBytes, enabled: m.enabled, sendEnabled: m.sendEnabled, receiveEnabled: m.receiveEnabled,
    passwordSetAt: m.passwordSetAt, createdAt: m.createdAt,
  };
}

const domainView = (d: MailDomain): ApiV1MailDomain => ({ id: d.id, name: d.name, enabled: d.enabled, status: d.status, mailboxCount: d.mailboxCount });

export const keyMail = {
  /** Mail domains, mailboxes (one page), plan limits and usage of the key's account. */
  async list(ctx: ApiKeyContext, q: KeyMailboxQuery = {}): Promise<ApiV1MailboxList> {
    requireScope(ctx, 'mail.mailboxes');
    const mailDomainId = q.mailDomainId || q.domain ? await keyMailDomainId(ctx, q) : undefined;
    const limit = Math.min(KEY_MAILBOX_PAGE_MAX, Math.max(1, Math.trunc(q.limit ?? 100) || 100));
    const offset = Math.max(0, Math.trunc(q.offset ?? 0) || 0);
    const [overview, domains, page] = await Promise.all([
      mailService.overview(ctx.actor, { accountId: ctx.accountId }),
      mailService.listDomains(ctx.actor, { accountId: ctx.accountId }),
      mailService.listMailboxes(ctx.actor, { accountId: ctx.accountId, mailDomainId, search: q.search?.trim() || undefined, limit, offset }),
    ]);
    return {
      hostsMailboxes: overview.hasMailboxes,
      hostname: overview.hostname,
      webmailUrl: overview.webmail.url,
      limits: overview.limits,
      usage: overview.usage,
      domains: domains.filter((d) => d.accountId === ctx.accountId).map(domainView),
      items: page.items.filter((m) => m.accountId === ctx.accountId).map(mailboxView),
      total: page.total,
    };
  },

  /** A mailbox in a mail domain of the account (the mail service's limits and checks); the password returned once. */
  async create(ctx: ApiKeyContext, req: Request, body: KeyMailboxCreate): Promise<ApiV1MailboxCreated> {
    await writable(ctx);
    const md = await loadMailDomain(ctx.actor, await keyMailDomainId(ctx, body), 'mail.manage');
    const localPart = assertLocalPart(body.localPart);
    const created = await mailService.createMailbox(asKeyRequest(req, ctx), ctx.actor, {
      mailDomainId: md.id, localPart, password: body.password || null,
      ...(body.quotaMb !== undefined ? { quotaMb: body.quotaMb } : {}),
      ...(body.displayName !== undefined ? { displayName: body.displayName?.trim() || null } : {}),
    });
    const { generatedPassword, ...mailbox } = created;
    return { mailbox: mailboxView(mailbox), password: generatedPassword };
  },

  /** A new password (given, else generated and returned once). Gate mail.mailbox_password. */
  async resetPassword(ctx: ApiKeyContext, req: Request, ref: KeyMailboxRef, body: { password?: string | null } = {}): Promise<ApiV1MailboxPassword> {
    await writable(ctx);
    const mb = await keyMailbox(ctx, ref);
    assertServed(mb.account_status);
    if (body.password) assertMailPasswordAcceptable(body.password);
    const r = await keyGated(ctx, req, passwordGate(mb, body.password),
      () => mailService.setPassword(asKeyRequest(req, ctx), ctx.actor, mb.id, { password: body.password || null }));
    return { mailbox: { id: mb.id, address: mb.address }, password: r.password };
  },

  /**
   * Deletes a mailbox and its mail (a tombstone: logins and delivery stop at the next sync, the data is purged after
   * the grace period). Gate mail.mailbox_delete: by default the key's owner confirms it with his code (428).
   */
  async remove(ctx: ApiKeyContext, req: Request, ref: KeyMailboxRef): Promise<{ deleted: true; id: number; address: string }> {
    await writable(ctx);
    const mb = await keyMailbox(ctx, ref);
    await keyGated(ctx, req, { action: 'mail.mailbox_delete', target: mailTarget(mb), params: { mailbox: mb.address } },
      () => mailService.deleteMailbox(asKeyRequest(req, ctx), ctx.actor, mb.id, mb.address));
    return { deleted: true, id: mb.id, address: mb.address };
  },
};
