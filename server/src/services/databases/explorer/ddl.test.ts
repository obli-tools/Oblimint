import { test } from 'node:test';
import assert from 'node:assert/strict';
import type { DbxColumn, DbxTableInfo } from '@oblimint/shared';
import type { AppError } from '../../../middleware/errorHandler';
import { buildDdl, checkType, columnSql, renderDefault } from './ddl';

// DDL generation of the explorer, per engine (validated against real servers by the e2e harness).

const col = (name: string, type: string, extra: Partial<DbxColumn> = {}): DbxColumn => ({
  name, type, nullable: true, default: null, primary: false, autoIncrement: false, comment: null, binary: false, ...extra,
});

function info(family: 'mysql' | 'postgresql', name = 'items', columns?: DbxColumn[]): DbxTableInfo {
  return {
    table: { id: name, name, schema: family === 'postgresql' ? 'public' : null, kind: 'table', rows: 0, bytes: 0, engine: null, comment: null },
    columns: columns ?? [
      col('id', family === 'mysql' ? 'int(11)' : 'integer', { nullable: false, primary: true, autoIncrement: true, identity: true }),
      col('label', family === 'mysql' ? 'varchar(20)' : 'character varying(20)'),
    ],
    primaryKey: ['id'], ddl: null,
    indexes: [
      { name: family === 'mysql' ? 'PRIMARY' : `${name}_pkey`, columns: ['id'], unique: true, primary: true, definition: null, constraint: true },
      { name: 'ix_label', columns: ['label'], unique: false, primary: false, definition: null },
    ],
    foreignKeys: [{ name: 'fk_x', columns: ['label'], refTable: 'other', refColumns: ['code'], onDelete: 'CASCADE', onUpdate: 'NO ACTION' }],
  };
}
const code = (e: unknown) => (e as AppError).code;

test('types: grammar accepted, injections refused', () => {
  for (const ok of ['int', 'int unsigned zerofill', 'varchar(255)', 'numeric(10, 2)', 'timestamp(3) with time zone', 'character varying(20)', 'double precision',
    "enum('a','b''c')", 'varchar(20) character set utf8mb4 collate utf8mb4_bin']) {
    assert.equal(typeof checkType('mysql', ok), 'string', ok);
  }
  for (const ok of ['text[]', 'integer[][]', 'public.my_type', 'timestamptz']) assert.equal(typeof checkType('postgresql', ok), 'string', ok);
  for (const bad of ['int; DROP TABLE x', 'int -- c', "enum('a\\')", 'int default 5', 'int primary key', 'int/*x*/', '(5)', 'int)', "enum('a", 'int not null',
    'varchar(20) collate "x"', 'text[]', 'int generated always as (1)', 'int comment \'x\'']) {
    assert.throws(() => checkType('mysql', bad), (e) => code(e) === 'invalidDdl', bad);
  }
});

test('defaults: literals quoted per engine, expressions from a list', () => {
  assert.equal(renderDefault('mysql', { kind: 'literal', value: "it's \\ ok" }), "'it\\'s \\\\ ok'");
  assert.equal(renderDefault('postgresql', { kind: 'literal', value: "it's" }), "'it''s'");
  assert.equal(renderDefault('mysql', { kind: 'expression', value: 'CURRENT_TIMESTAMP' }), 'CURRENT_TIMESTAMP');
  assert.equal(renderDefault('mysql', { kind: 'expression', value: 'uuid()' }), '(uuid())');
  assert.equal(renderDefault('postgresql', { kind: 'expression', value: 'gen_random_uuid()' }), 'gen_random_uuid()');
  assert.equal(renderDefault('postgresql', { kind: 'expression', value: '-1.5' }), '-1.5');
  assert.equal(renderDefault('mysql', { kind: 'null' }), 'NULL');
  assert.equal(renderDefault('mysql', null), null);
  assert.throws(() => renderDefault('mysql', { kind: 'expression', value: '(SELECT password FROM users)' }), (e) => code(e) === 'invalidDdl');
  assert.throws(() => renderDefault('postgresql', { kind: 'expression', value: 'now()); DROP TABLE x; --' }), (e) => code(e) === 'invalidDdl');
});

test('columns: identifiers quoted (quote characters doubled), MySQL comment escaped, bad names refused', () => {
  assert.equal(columnSql('mysql', { name: 'we`ird', type: 'int', nullable: false, autoIncrement: true, comment: "a'b" }), "`we``ird` int NOT NULL AUTO_INCREMENT COMMENT 'a\\'b'");
  assert.equal(columnSql('postgresql', { name: 'we"ird', type: 'bigint', nullable: false, autoIncrement: true }), '"we""ird" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL');
  assert.throws(() => columnSql('mysql', { name: 'x', type: 'varchar(10)', nullable: true, autoIncrement: true }), (e) => code(e) === 'invalidDdl');
  assert.throws(() => columnSql('mysql', { name: 'x ', type: 'int', nullable: true }), (e) => code(e) === 'invalidDdl');
  assert.throws(() => columnSql('postgresql', { name: 'x'.repeat(64), type: 'int', nullable: true }), (e) => code(e) === 'invalidDdl');
  assert.throws(() => columnSql('postgresql', { name: 'a\0b', type: 'int', nullable: true }), (e) => code(e) === 'invalidDdl');
});

test('MySQL: create / rename / drop / truncate / columns / indexes / keys / objects', () => {
  const ctx = { family: 'mysql' as const, table: info('mysql'), refTable: info('mysql', 'other', [col('code', 'varchar(20)')]) };
  const one = (r: Parameters<typeof buildDdl>[0]) => buildDdl(r, ctx).statements;
  assert.deepEqual(one({
    op: 'createTable', name: 't',
    columns: [{ name: 'id', type: 'int', nullable: false, autoIncrement: true }, { name: 'n', type: 'varchar(10)', nullable: true, default: { kind: 'null' }, comment: 'c' }],
    primaryKey: ['id'], comment: 'tbl',
  }), ["CREATE TABLE `t` (\n  `id` int NOT NULL AUTO_INCREMENT,\n  `n` varchar(10) NULL DEFAULT NULL COMMENT 'c',\n  PRIMARY KEY (`id`)\n) COMMENT='tbl'"]);
  assert.throws(() => one({ op: 'createTable', name: 't', columns: [{ name: 'a', type: 'int', nullable: true }, { name: 'a', type: 'int', nullable: true }] }), (e) => code(e) === 'invalidDdl');
  assert.deepEqual(one({ op: 'renameTable', table: 'items', newName: 'goods' }), ['RENAME TABLE `items` TO `goods`']);
  assert.deepEqual(one({ op: 'dropTable', table: 'items', confirm: 'items' }), ['DROP TABLE `items`']);
  assert.deepEqual(one({ op: 'truncateTable', table: 'items', confirm: 'items' }), ['TRUNCATE TABLE `items`']);
  assert.throws(() => one({ op: 'truncateTable', table: 'items', confirm: 'Items' }), (e) => code(e) === 'confirmMismatch');
  assert.deepEqual(one({ op: 'addColumn', table: 'items', column: { name: 'qty', type: 'int unsigned', nullable: false, default: { kind: 'literal', value: '0' } }, after: 'id' }),
    ["ALTER TABLE `items` ADD COLUMN `qty` int unsigned NOT NULL DEFAULT '0' AFTER `id`"]);
  assert.deepEqual(one({ op: 'addColumn', table: 'items', column: { name: 'first', type: 'int', nullable: true }, after: '' }), ['ALTER TABLE `items` ADD COLUMN `first` int NULL FIRST']);
  assert.throws(() => one({ op: 'addColumn', table: 'items', column: { name: 'label', type: 'int', nullable: true } }), (e) => code(e) === 'invalidDdl');
  // CHANGE keeps the collation and ON UPDATE of the current column.
  const withExtras = info('mysql', 'items', [col('id', 'int', { primary: true }), col('label', 'varchar(20)', { collation: 'utf8mb4_bin' }), col('at', 'timestamp', { extra: 'on update current_timestamp()' })]);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'label', def: { name: 'title', type: 'varchar(50)', nullable: false } }, { family: 'mysql', table: withExtras }).statements,
    ['ALTER TABLE `items` CHANGE COLUMN `label` `title` varchar(50) COLLATE utf8mb4_bin NOT NULL']);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'at', def: { name: 'at', type: 'timestamp', nullable: true, default: { kind: 'expression', value: 'current_timestamp()' } } }, { family: 'mysql', table: withExtras }).statements,
    ['ALTER TABLE `items` CHANGE COLUMN `at` `at` timestamp NULL DEFAULT current_timestamp() ON UPDATE CURRENT_TIMESTAMP()']);
  assert.deepEqual(one({ op: 'dropColumn', table: 'items', column: 'label' }), ['ALTER TABLE `items` DROP COLUMN `label`']);
  assert.throws(() => one({ op: 'dropColumn', table: 'items', column: 'nope' }), (e) => code(e) === 'unknownColumn');
  assert.deepEqual(one({ op: 'createIndex', table: 'items', name: 'ux', columns: ['label', 'id'], unique: true }), ['CREATE UNIQUE INDEX `ux` ON `items` (`label`, `id`)']);
  assert.throws(() => one({ op: 'createIndex', table: 'items', name: 'ux', columns: ['label', 'label'], unique: true }), (e) => code(e) === 'invalidDdl');
  assert.deepEqual(one({ op: 'dropIndex', table: 'items', name: 'ix_label' }), ['DROP INDEX `ix_label` ON `items`']);
  assert.deepEqual(one({ op: 'dropIndex', table: 'items', name: 'PRIMARY' }), ['ALTER TABLE `items` DROP PRIMARY KEY']);
  assert.deepEqual(one({ op: 'setPrimaryKey', table: 'items', columns: ['id', 'label'] }), ['ALTER TABLE `items` DROP PRIMARY KEY, ADD PRIMARY KEY (`id`, `label`)']);
  assert.deepEqual(one({ op: 'addForeignKey', table: 'items', name: 'fk_o', columns: ['label'], refTable: 'other', refColumns: ['code'], onDelete: 'SET NULL', onUpdate: 'CASCADE' }),
    ['ALTER TABLE `items` ADD CONSTRAINT `fk_o` FOREIGN KEY (`label`) REFERENCES `other` (`code`) ON DELETE SET NULL ON UPDATE CASCADE']);
  assert.throws(() => one({ op: 'addForeignKey', table: 'items', name: 'f', columns: ['label'], refTable: 'other', refColumns: ['code'], onDelete: 'DROP' as never, onUpdate: 'CASCADE' }), (e) => code(e) === 'invalidDdl');
  assert.throws(() => one({ op: 'addForeignKey', table: 'items', name: 'f', columns: ['label'], refTable: 'other', refColumns: ['nope'], onDelete: 'CASCADE', onUpdate: 'CASCADE' }), (e) => code(e) === 'unknownColumn');
  assert.deepEqual(one({ op: 'dropForeignKey', table: 'items', name: 'fk_x' }), ['ALTER TABLE `items` DROP FOREIGN KEY `fk_x`']);
  const obj = { kind: 'procedure' as const, id: 'p', name: 'p', schema: null, table: null, detail: null, definer: null, ephemeralDefiner: false };
  assert.deepEqual(buildDdl({ op: 'dropObject', kind: 'procedure', id: 'p', confirm: 'p' }, { family: 'mysql', object: obj }).statements, ['DROP PROCEDURE `p`']);
  assert.throws(() => buildDdl({ op: 'dropObject', kind: 'procedure', id: 'p', confirm: 'q' }, { family: 'mysql', object: obj }), (e) => code(e) === 'confirmMismatch');
});

test('PostgreSQL: schema-qualified, ALTER COLUMN pieces, identity, constraints, comments', () => {
  const ctx = { family: 'postgresql' as const, table: info('postgresql'), refTable: info('postgresql', 'other', [col('code', 'text')]) };
  const one = (r: Parameters<typeof buildDdl>[0]) => buildDdl(r, ctx).statements;
  assert.deepEqual(one({
    op: 'createTable', name: 'T',
    columns: [{ name: 'id', type: 'bigint', nullable: false, autoIncrement: true }, { name: 'at', type: 'timestamptz', nullable: false, default: { kind: 'expression', value: 'now()' }, comment: "c'1" }],
    primaryKey: ['id'], comment: 'tbl',
  }), ['CREATE TABLE "T" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "at" timestamptz NOT NULL DEFAULT now(),\n  PRIMARY KEY ("id")\n)', 'COMMENT ON TABLE "T" IS \'tbl\'', 'COMMENT ON COLUMN "T"."at" IS \'c\'\'1\'']);
  assert.deepEqual(one({ op: 'renameTable', table: 'items', newName: 'goods' }), ['ALTER TABLE "public"."items" RENAME TO "goods"']);
  assert.deepEqual(one({ op: 'modifyColumn', table: 'items', column: 'label', def: { name: 'title', type: 'text', nullable: false, default: { kind: 'literal', value: 'x' }, comment: 'hello' } }), [
    'ALTER TABLE "public"."items" RENAME COLUMN "label" TO "title"',
    'ALTER TABLE "public"."items" ALTER COLUMN "title" TYPE text USING "title"::text',
    'ALTER TABLE "public"."items" ALTER COLUMN "title" SET DEFAULT \'x\'',
    'ALTER TABLE "public"."items" ALTER COLUMN "title" SET NOT NULL',
    'COMMENT ON COLUMN "public"."items"."title" IS \'hello\'',
  ]);
  // Identity removed; a serial column keeps its nextval() default.
  assert.deepEqual(one({ op: 'modifyColumn', table: 'items', column: 'id', def: { name: 'id', type: 'integer', nullable: false } }), ['ALTER TABLE "public"."items" ALTER COLUMN "id" DROP IDENTITY IF EXISTS']);
  const serial = info('postgresql', 'items', [col('id', 'integer', { nullable: false, autoIncrement: true, default: "nextval('items_id_seq'::regclass)" })]);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'id', def: { name: 'id', type: 'integer', nullable: false, autoIncrement: true } }, { family: 'postgresql', table: serial }).statements, []);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'id', def: { name: 'id', type: 'integer', nullable: false } }, { family: 'postgresql', table: serial }).statements,
    ['ALTER TABLE "public"."items" ALTER COLUMN "id" DROP DEFAULT']);
  const plain = info('postgresql', 'items', [col('n', 'integer', { default: '0' })]);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'n', def: { name: 'n', type: 'integer', nullable: true, autoIncrement: true } }, { family: 'postgresql', table: plain }).statements,
    ['ALTER TABLE "public"."items" ALTER COLUMN "n" DROP DEFAULT', 'ALTER TABLE "public"."items" ALTER COLUMN "n" ADD GENERATED BY DEFAULT AS IDENTITY']);
  assert.deepEqual(buildDdl({ op: 'modifyColumn', table: 'items', column: 'n', def: { name: 'n', type: 'integer', nullable: true, default: { kind: 'literal', value: '0' } } }, { family: 'postgresql', table: plain }).statements, [], 'same default: nothing');
  assert.deepEqual(one({ op: 'dropIndex', table: 'items', name: 'ix_label' }), ['DROP INDEX "public"."ix_label"']);
  assert.deepEqual(one({ op: 'dropIndex', table: 'items', name: 'items_pkey' }), ['ALTER TABLE "public"."items" DROP CONSTRAINT "items_pkey"']);
  assert.deepEqual(one({ op: 'setPrimaryKey', table: 'items', columns: [] }), ['ALTER TABLE "public"."items" DROP CONSTRAINT "items_pkey"']);
  assert.deepEqual(one({ op: 'addForeignKey', table: 'items', name: 'fk', columns: ['label'], refTable: 'other', refColumns: ['code'], onDelete: 'RESTRICT', onUpdate: 'NO ACTION' }),
    ['ALTER TABLE "public"."items" ADD CONSTRAINT "fk" FOREIGN KEY ("label") REFERENCES "public"."other" ("code") ON DELETE RESTRICT ON UPDATE NO ACTION']);
  assert.deepEqual(one({ op: 'dropForeignKey', table: 'items', name: 'fk_x' }), ['ALTER TABLE "public"."items" DROP CONSTRAINT "fk_x"']);
  assert.deepEqual(one({ op: 'truncateTable', table: 'items', confirm: 'items' }), ['TRUNCATE TABLE "public"."items"']);
  const fn = { kind: 'function' as const, id: 'f(integer, text)', name: 'f', schema: 'public', table: null, detail: null, args: 'integer, text', definer: null, ephemeralDefiner: false };
  assert.deepEqual(buildDdl({ op: 'dropObject', kind: 'function', id: 'f(integer, text)', confirm: 'f' }, { family: 'postgresql', object: fn }).statements, ['DROP FUNCTION "public"."f"(integer, text)']);
  const trg = { ...fn, kind: 'trigger' as const, name: 'tg', table: 'items', args: null };
  assert.deepEqual(buildDdl({ op: 'dropObject', kind: 'trigger', id: 'items:tg', confirm: 'tg' }, { family: 'postgresql', object: trg }).statements, ['DROP TRIGGER "tg" ON "public"."items"']);
  const v = info('postgresql', 'v');
  const view = { ...v, table: { ...v.table, kind: 'view' as const, materialized: true } };
  assert.deepEqual(buildDdl({ op: 'dropTable', table: 'v', confirm: 'v' }, { family: 'postgresql', table: view }).statements, ['DROP MATERIALIZED VIEW "public"."v"']);
});

test('MySQL: modifyColumn refuses generated / invisible columns (CHANGE COLUMN would drop the expression / the flag)', () => {
  const t = info('mysql', 'items', [
    col('id', 'int(11)', { nullable: false, primary: true }),
    col('a', 'int(11)'),
    col('b', 'int(11)', { extra: 'STORED GENERATED' }),
    col('v', 'int(11)', { extra: 'VIRTUAL GENERATED' }),
    col('h', 'int(11)', { extra: 'INVISIBLE' }),
    col('at', 'datetime', { extra: 'DEFAULT_GENERATED on update CURRENT_TIMESTAMP' }),
  ]);
  const ctx = { family: 'mysql' as const, table: t };
  for (const c of ['b', 'v', 'h']) {
    assert.throws(() => buildDdl({ op: 'modifyColumn', table: 'items', column: c, def: { name: c, type: 'bigint', nullable: true } }, ctx),
      (e) => code(e) === 'invalidDdl' && /console/.test((e as AppError).message), c);
  }
  // A plain column, or a default expression (DEFAULT_GENERATED), is still changed with the form.
  assert.equal(buildDdl({ op: 'modifyColumn', table: 'items', column: 'a', def: { name: 'a', type: 'bigint', nullable: true } }, ctx).statements.length, 1);
  assert.equal(buildDdl({ op: 'modifyColumn', table: 'items', column: 'at', def: { name: 'at', type: 'datetime', nullable: true } }, ctx).statements.length, 1);
});
