import { createHash } from 'crypto';
import type { DnsRecordOrigin, DnsRecordType, MailDnsFixBlockedReason, MailDnsFixItem, MailDnsFixKind, MailDnsFixRecord } from '@oblimint/shared';
import { applyOverrides, inZone, relativeTo, txtKind, type GeneratedRecord } from '../../dns/records';
import { zoneRecordsOf, type MailRecordSpec } from './records';

// ─────────────────────────────────────────────────────────────────────────────
// PURE fix plan of the mail records of a HOSTED zone (no I/O → fixPlan.test.ts).
//
// The mail DNS contributor generates MX / SPF / DKIM / DMARC as auto records;
// dns/records.applyOverrides drops an auto record as soon as a manual /
// template / system record holds the same name + type (TXT: same TXT kind) or
// a CNAME sits at that name — typically the provider records of an imported
// zone. The plan says, per expected record (one item per kind + name):
//   - before: the stored records hiding / replacing it (removed by the fix);
//   - after:  what our name servers serve once they are gone (the expected
//             record, generated by the contributor);
//   - status: fix | ok (already served) | blocked (reason).
// The simulation re-runs applyOverrides without the removed rows: an item is
// 'fix' only when the expected record is then really generated AND kept.
// Never touched: system records (ACME / ownership), apex TXT of another kind
// (site verifications), a CNAME at the mail domain name (its website).
// ─────────────────────────────────────────────────────────────────────────────

export const FIX_KINDS: readonly MailDnsFixKind[] = ['mx', 'spf', 'dkim', 'dmarc'];

/** A stored row of the zone (dns_records). */
export interface FixZoneRow {
  id: number;
  name: string;
  type: DnsRecordType;
  content: string;
  ttl: number;
  priority: number | null;
  origin: DnsRecordOrigin;
  disabled: boolean;
  expiresAt?: Date | string | null;
}

export interface FixPlanInput {
  /** Zone apex (lower case, no trailing dot). */
  zone: string;
  defaultTtl: number;
  /** Mail domain FQDN (lower case). */
  domain: string;
  /** Expected records of the mail domain (mailRecordSpecs). */
  specs: MailRecordSpec[];
  /** Every stored row of the zone. */
  rows: FixZoneRow[];
  /** Auto records the zone would get BEFORE overrides (store.generatedAuto: contributors applied). */
  generated: GeneratedRecord[];
  now?: Date;
}

export function fixItemId(kind: MailDnsFixKind, fqdn: string): string {
  return `${kind}:${fqdn.toLowerCase()}`;
}

function isServed(r: FixZoneRow, now: Date): boolean {
  if (r.disabled) return false;
  if (r.expiresAt && new Date(r.expiresAt).getTime() <= now.getTime()) return false;
  return true;
}

const pairKey = (r: { content: string; priority: number | null }) => `${r.content}|${r.priority ?? ''}`;

/** Does `r` (at the item's name) belong to the item's rrset (type, TXT kind)? */
function sameRrset(r: Pick<FixZoneRow, 'name' | 'type' | 'content'>, type: 'MX' | 'TXT', kind: MailDnsFixKind): boolean {
  if (r.type !== type) return false;
  return type !== 'TXT' || txtKind(r.name, r.content) === kind;
}

/** SPF terms of `removed` that `kept` no longer holds (qualifier '+' dropped; `v=spf1` and `all` ignored). */
export function lostSpfTerms(removed: string[], kept: string[]): string[] {
  const terms = (s: string) => s.trim().toLowerCase().split(/\s+/).slice(1).map((t) => t.replace(/^\+/, '')).filter((t) => t && !/^[~?-]?all$/.test(t));
  const keep = new Set(kept.flatMap(terms));
  const out: string[] = [];
  for (const t of removed.flatMap(terms)) if (!keep.has(t) && !out.includes(t)) out.push(t);
  return out;
}

function fingerprint(item: Pick<MailDnsFixItem, 'status' | 'before' | 'after'>): string {
  const payload = JSON.stringify({
    s: item.status,
    b: item.before.map((r) => [r.id, r.type, r.content, r.priority, r.origin, r.disabled]),
    a: item.after.map((r) => [r.content, r.priority]),
  });
  return createHash('sha256').update(payload).digest('hex').slice(0, 16);
}

/** Every MX / SPF / DKIM / DMARC item of the mail domain in that zone, in the order of the specs. */
export function buildFixPlan(input: FixPlanInput): MailDnsFixItem[] {
  const now = input.now ?? new Date();
  const zone = input.zone.toLowerCase();
  const domainRel = inZone(input.domain.toLowerCase(), zone) ? relativeTo(input.domain.toLowerCase(), zone) : null;
  // Expected records grouped per (kind, FQDN), projected into the zone (validated like the contributor does).
  const groups = new Map<string, { kind: MailDnsFixKind; fqdn: string; type: 'MX' | 'TXT'; rel: string; expected: GeneratedRecord[] }>();
  for (const s of input.specs) {
    if (!(FIX_KINDS as readonly string[]).includes(s.kind) || !s.zone) continue;
    if (s.type !== 'MX' && s.type !== 'TXT') continue;
    const { records } = zoneRecordsOf([s], zone, input.defaultTtl);
    if (records.length === 0) continue;
    const kind = s.kind as MailDnsFixKind;
    const id = fixItemId(kind, s.fqdn);
    let g = groups.get(id);
    if (!g) {
      g = { kind, fqdn: s.fqdn.toLowerCase(), type: s.type, rel: records[0].name, expected: [] };
      groups.set(id, g);
    }
    g.expected.push(records[0]);
  }

  const nonAuto = input.rows.filter((r) => r.origin !== 'auto');
  const items: MailDnsFixItem[] = [];
  for (const [id, g] of groups) {
    const atName = input.rows.filter((r) => r.name === g.rel);
    // What the zone serves now for this rrset (any origin).
    const served = atName.filter((r) => isServed(r, now) && sameRrset(r, g.type, g.kind));
    const servedCname = atName.some((r) => r.type === 'CNAME' && isServed(r, now));
    const wanted = new Set(g.expected.map(pairKey));
    const servedKeys = new Set(served.map(pairKey));
    const alreadyServed = !servedCname && served.length > 0 && servedKeys.size === wanted.size && [...wanted].every((k) => servedKeys.has(k));

    // Stored rows hiding the expected auto record: same rrset (non-auto) or a CNAME at the name.
    const shadows = nonAuto.filter((r) => r.name === g.rel && (r.type === 'CNAME' || sameRrset(r, g.type, g.kind)));
    const after = g.expected.map((r) => ({ content: r.content, priority: r.priority }));
    const toRecord = (r: FixZoneRow): MailDnsFixRecord => ({
      id: r.id, type: r.type, content: r.content, priority: r.priority, origin: r.origin, disabled: !!r.disabled, served: isServed(r, now),
    });

    let status: MailDnsFixItem['status'];
    let reason: MailDnsFixBlockedReason | null = null;
    let removable = shadows.filter((r) => r.origin === 'manual' || r.origin === 'template');
    if (alreadyServed) {
      status = 'ok';
      removable = [];
    } else {
      const generatedKeys = new Set(input.generated.filter((r) => r.name === g.rel && r.type === g.type).map(pairKey));
      const removedIds = new Set(removable.map((r) => r.id));
      const othersAfter = nonAuto.filter((r) => !removedIds.has(r.id));
      const keptAfter = new Set(applyOverrides(input.generated, othersAfter).filter((r) => r.name === g.rel && r.type === g.type).map(pairKey));
      if (![...wanted].every((k) => generatedKeys.has(k))) {
        status = 'blocked';
        reason = 'notGenerated';
      } else if (domainRel !== null && g.rel === domainRel && shadows.some((r) => r.type === 'CNAME')) {
        // A CNAME at the mail domain name carries its website: never removed here.
        status = 'blocked';
        reason = 'cnameAtName';
      } else if (shadows.some((r) => r.origin === 'system')) {
        status = 'blocked';
        reason = 'systemRecord';
      } else if (![...wanted].every((k) => keptAfter.has(k))) {
        status = 'blocked';
        reason = 'stillHidden';
      } else {
        status = 'fix';
      }
      if (status === 'blocked') removable = [];
    }
    const before = (status === 'fix' ? removable : shadows).map(toRecord);
    const item: Omit<MailDnsFixItem, 'fingerprint'> = {
      id,
      kind: g.kind,
      name: g.fqdn,
      type: g.type,
      status,
      reason,
      before,
      after,
      lostSpfTerms: g.kind === 'spf' && status === 'fix'
        ? lostSpfTerms(before.filter((r) => r.type === 'TXT').map((r) => r.content), after.map((r) => r.content))
        : [],
    };
    items.push({ ...item, fingerprint: fingerprint(item) });
  }
  return items;
}

/** Ids of the stored rows removed by the given 'fix' items (union). */
export function rowsToRemove(items: MailDnsFixItem[]): number[] {
  const ids = new Set<number>();
  for (const it of items) if (it.status === 'fix') for (const r of it.before) ids.add(r.id);
  return [...ids];
}
