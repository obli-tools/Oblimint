/** Personal Sieve location of a mailbox that may not send: never exists (outside every volume). */
export const SIEVE_DISABLED = '/nonexistent/oblimint-sieve-disabled';
import {
  assertAddress, assertDomain, assertHostname, assertInt, assertLocalPart, assertNumber, assertPasswordHash, assertSafePath,
  assertSelector, hostCidr, networksExcluding, RenderError,
} from './validate';

// ─────────────────────────────────────────────────────────────────────────────
// PURE rendering of mail/config/postfix-dovecot/ from the desired state
// (docs/P4-PLAN.md §5.2) — render.test.ts. No I/O, no clock (ctx.now), no
// randomness: the same state always gives the same files, hence the same
// fingerprint (idempotent sync, no reload when nothing changed).
//
// Errors: a global value that cannot be rendered (host name, scores…) throws
// RenderError (the driver answers invalidState); an invalid domain / mailbox
// / alias / key / certificate is SKIPPED and reported in domainErrors under
// its domain, the rest is rendered (driver.ts MailSyncResult.domainErrors).
// Messages never contain a hash, a key, a body or the fingerprint (MA4).
// ─────────────────────────────────────────────────────────────────────────────

export interface RenderContext {
  now: Date;
  /** Subnets of MAIL_NETWORK (IPAM): Dovecot login_trusted_networks. */
  mailSubnets: string[];
  /** Gateway address(es) of MAIL_NETWORK: excluded from every trusted network (userland proxy, R-MAIL-CLIENTIP). */
  mailGateways: string[];
  /** Host directory of the mail certificates (paths.hostPaths.mailCerts()): state.tls paths must be under it. */
  hostCertsDir: string;
  /**
   * Largest stream the shared scanner's clamd accepts and scans (settings
   * scanner.maxFileSizeMb, MiB). Rspamd never sends a larger message (clamd
   * would answer "INSTREAM size limit exceeded"); null ⇒ unknown, the
   * documented default (32) is assumed.
   */
  clamdMaxFileSizeMb?: number | null;
}

export interface RenderOutput {
  /** Relative path (POSIX) → content, sorted by path. */
  files: Map<string, string>;
  /** '<domain>/<selector>.key' → key file content (signing keys of active domains only). */
  dkimKeys: Map<string, string>;
  /** Every mailbox the engine knows (userdb): mass-removal guard. */
  mailboxes: string[];
  counts: { domains: number; mailboxes: number; aliases: number };
  domainErrors: Record<string, string>;
  /** sha256 of files + keys (never shown, never logged in an error). */
  fingerprint: string;
}

interface Box {
  m: DesiredMailbox;
  domainActive: boolean;
}

const line = (key: string, value: string): string => `${key} ${value}`;
const header = (what: string): string => `# Generated by Oblimint (postfix-dovecot) — ${what}. Do not edit: rewritten at every sync.`;
const file = (title: string, lines: string[]): string => `${[header(title), ...lines].join('\n')}\n`;
const byString = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

/** Host path of a certificate file → its path in the engine container (mail/certs is mounted at C_CERTS). */
export function containerCertPath(hostPath: string, hostCertsDir: string): string {
  const root = hostCertsDir.replace(/\\/g, '/').replace(/\/+$/, '');
  const p = String(hostPath ?? '').replace(/\\/g, '/');
  if (!p.startsWith(`${root}/`)) throw new RenderError('certificate outside the mail certificate directory');
  return assertSafePath(`${C_CERTS}/${p.slice(root.length + 1)}`, 'certificate path');
}

/** DKIM private key as Rspamd loads it: RSA → PEM as is; ed25519 → base64 of the 32-byte seed. */
export function dkimKeyFile(pem: string, algorithm: 'rsa-2048' | 'ed25519'): string {
  if (typeof pem !== 'string' || pem.length > 16_384 || !/^-----BEGIN (?:RSA )?PRIVATE KEY-----\r?\n[A-Za-z0-9+/=\r\n]+-----END (?:RSA )?PRIVATE KEY-----\s*$/.test(pem)) {
    throw new RenderError('invalid DKIM private key');
  }
  let key: crypto.KeyObject;
  try {
    key = crypto.createPrivateKey(pem);
  } catch {
    throw new RenderError('invalid DKIM private key');
  }
  if (algorithm === 'ed25519') {
    if (key.asymmetricKeyType !== 'ed25519') throw new RenderError('DKIM key is not ed25519');
    const jwk = key.export({ format: 'jwk' }) as { d?: string };
    if (!jwk.d) throw new RenderError('invalid DKIM private key');
    return `${Buffer.from(jwk.d, 'base64url').toString('base64')}\n`;
  }
  if (key.asymmetricKeyType !== 'rsa') throw new RenderError('DKIM key is not RSA');
  return pem.endsWith('\n') ? pem : `${pem}\n`;
}

function collectErrors() {
  const errors: Record<string, string> = {};
  return {
    errors,
    add(domain: string, message: string) {
      const key = typeof domain === 'string' && domain ? domain.slice(0, 253) : '(unknown)';
      errors[key] = errors[key] ? `${errors[key]}; ${message}` : message;
    },
  };
}

const errMsg = (err: unknown): string => (err instanceof RenderError ? err.message : 'invalid value');

export function renderConfig(state: MailDesiredState, ctx: RenderContext): RenderOutput {
  const s = state.settings;
  const hostname = assertHostname(String(s.hostname ?? '').toLowerCase());
  const maxSizeMb = assertInt(s.maxMessageSizeMb, 1, 2048, 'maximum message size');
  const tag = assertNumber(s.spamTagScore, 0, 1000, 'spam tag score');
  const reject = assertNumber(s.spamRejectScore, 0, 1000, 'spam reject score');
  if (!(tag < reject)) throw new RenderError('the spam tag score must be lower than the reject score');
  const trustedNets = networksExcluding(ctx.mailSubnets, ctx.mailGateways);
  const err = collectErrors();

  // ── domains ──
  const domains = new Map<string, { active: boolean; catchAll: string | null; maxMb: number }>();
  for (const d of state.domains) {
    try {
      const name = assertDomain(d.name);
      if (domains.has(name)) throw new RenderError('duplicate mail domain');
      const maxMb = Math.min(maxSizeMb, assertInt(d.maxMessageSizeMb, 1, 2048, 'maximum message size'));
      domains.set(name, { active: !!d.active, catchAll: d.catchAll ? assertAddress(d.catchAll, 'catch-all address') : null, maxMb });
    } catch (e) {
      err.add(d?.name, errMsg(e));
    }
  }

  // ── mailboxes ──
  const boxes = new Map<string, Box>();
  for (const m of state.mailboxes) {
    try {
      const address = assertAddress(m.address);
      const domain = assertDomain(m.domain);
      assertLocalPart(m.localPart);
      if (address !== `${m.localPart}@${domain}`) throw new RenderError('mailbox address does not match its domain');
      const d = domains.get(domain);
      if (!d) throw new RenderError('mailbox of an unknown mail domain');
      if (boxes.has(address)) throw new RenderError('duplicate mailbox');
      assertPasswordHash(m.passwordHash, m.passwordScheme);
      if (m.quotaMb !== null) assertInt(m.quotaMb, 1, 100_000_000, 'quota');
      if (m.sendPerHour !== null) assertInt(m.sendPerHour, 0, 10_000_000, 'hourly send limit');
      if (m.forward) {
        if (!Array.isArray(m.forward.targets) || m.forward.targets.length === 0 || m.forward.targets.length > 50) throw new RenderError('invalid forwarding');
        m.forward.targets.forEach((t) => assertAddress(t, 'forwarding target'));
      }
      boxes.set(address, { m, domainActive: d.active });
    } catch (e) {
      err.add(m?.domain, `${String(m?.localPart ?? '?').slice(0, 64)}: ${errMsg(e)}`);
    }
  }

  // ── aliases ──
  const aliases = new Map<string, string[]>();
  for (const a of state.aliases) {
    const dom = String(a?.address ?? '').split('@')[1] ?? '';
    try {
      const address = assertAddress(a.address);
      const d = domains.get(address.split('@')[1]);
      if (!d) throw new RenderError('alias of an unknown mail domain');
      if (boxes.has(address)) throw new RenderError('an alias cannot have the address of a mailbox');
      if (aliases.has(address)) throw new RenderError('duplicate alias');
      if (!Array.isArray(a.targets) || a.targets.length === 0 || a.targets.length > 50) throw new RenderError('invalid alias targets');
      aliases.set(address, [...new Set(a.targets.map((t) => assertAddress(t, 'alias target')))]);
    } catch (e) {
      err.add(dom, `alias ${String(a?.address ?? '?').split('@')[0].slice(0, 64)}: ${errMsg(e)}`);
    }
  }

  const isActiveDomainOf = (addr: string): boolean => domains.get(addr.split('@')[1])?.active === true;
  /** Can a message to this address be delivered? A local mailbox that refuses mail is never a target (MA12). */
  const deliverable = (addr: string): boolean => {
    const b = boxes.get(addr);
    if (b) return b.domainActive && b.m.receiveEnabled;
    return true; // alias (expanded recursively by Postfix) or external address
  };

  // ── Postfix maps ──
  const vDomains: string[] = [];
  const vMailboxes: string[] = [];
  const vAliases: string[] = [];
  const recipientAccess: string[] = [];
  const senderAccess: string[] = [];
  const saslAccess: string[] = [];
  const owners = new Map<string, Set<string>>();
  const addOwner = (addr: string, login: string) => {
    if (!owners.has(addr)) owners.set(addr, new Set());
    owners.get(addr)!.add(login);
  };
  const canLogin = (b: Box | undefined): boolean => !!b && b.domainActive && b.m.loginEnabled;

  const domainNames = [...domains.keys()].sort(byString);
  const boxesOf = (domain: string) => [...boxes.values()].filter((b) => b.m.domain === domain).sort((x, y) => byString(x.m.address, y.m.address));
  const aliasesOf = (domain: string) => [...aliases.entries()].filter(([a]) => a.split('@')[1] === domain).sort((x, y) => byString(x[0], y[0]));

  let activeDomains = 0;
  let renderedAliases = 0;
  for (const name of domainNames) {
    const d = domains.get(name)!;
    if (!d.active) continue;
    activeDomains++;
    vDomains.push(line(name, 'OK'));
    for (const b of boxesOf(name)) {
      const addr = b.m.address;
      vMailboxes.push(line(addr, `${name}/${b.m.localPart}/`));
      if (!b.m.receiveEnabled) {
        recipientAccess.push(line(addr, 'REJECT 5.2.1 Mailbox unavailable'));
      } else if (b.m.forward) {
        const targets = b.m.forward.targets.filter((t) => t !== addr && deliverable(t));
        const dest = b.m.forward.keepCopy || targets.length === 0 ? [addr, ...targets] : targets;
        vAliases.push(line(addr, dest.join(',')));
      } else if (d.catchAll) {
        // identity: the catch-all below must not swallow an existing mailbox
        vAliases.push(line(addr, addr));
      }
      if (canLogin(b)) addOwner(addr, addr);
      if (!b.m.sendEnabled) {
        senderAccess.push(line(addr, 'REJECT 5.7.1 Sending is disabled for this mailbox'));
        saslAccess.push(line(addr, 'REJECT 5.7.1 Sending is disabled for this mailbox'));
      }
    }
    for (const [addr, targets] of aliasesOf(name)) {
      renderedAliases++;
      const live = targets.filter((t) => t !== addr && deliverable(t));
      if (live.length === 0) recipientAccess.push(line(addr, 'REJECT 5.1.1 Recipient address rejected'));
      else vAliases.push(line(addr, live.join(',')));
      // MA3: an alias may be used as sender by the mailboxes it delivers to.
      for (const t of targets) if (canLogin(boxes.get(t))) addOwner(addr, t);
      const sendOwners = targets.map((t) => boxes.get(t)).filter((b): b is Box => canLogin(b));
      if (sendOwners.length > 0 && sendOwners.every((b) => !b.m.sendEnabled)) {
        senderAccess.push(line(addr, 'REJECT 5.7.1 Sending is disabled for this address'));
      }
    }
    if (d.catchAll && deliverable(d.catchAll)) {
      vAliases.push(line(`@${name}`, d.catchAll));
    }
  }
  const senderLogin = [...owners.entries()].sort((x, y) => byString(x[0], y[0]))
    .map(([addr, set]) => line(addr, [...set].sort(byString).join(',')));

  // relay intake (10025): exact addresses only, never a subnet (MA2)
  const relayClients: string[] = [];
  for (const ip of [...new Set(state.relay?.relayAddresses ?? [])].sort(byString)) {
    try {
      relayClients.push(line(hostCidr(ip), 'OK'));
    } catch {
      err.add(hostname, 'invalid relay address ignored');
    }
  }

  // ── TLS (default certificate + SNI) ──
  let defaultCert: { cert: string; key: string } | null = null;
  const sni = new Map<string, { cert: string; key: string }>();
  const dovecotSni: Array<{ name: string; cert: string; key: string }> = [];
  const certs = [...(state.tls ?? [])].sort((a, b) => Number(b.isDefault) - Number(a.isDefault) || byString(a.names[0] ?? '', b.names[0] ?? ''));
  for (const c of certs) {
    try {
      const names = (c.names ?? []).map((n) => assertHostname(String(n).toLowerCase()));
      if (names.length === 0) throw new RenderError('certificate without names');
      const pair = { cert: containerCertPath(c.certPath, ctx.hostCertsDir), key: containerCertPath(c.keyPath, ctx.hostCertsDir) };
      if (c.isDefault && !defaultCert) defaultCert = pair;
      for (const n of names) {
        if (sni.has(n)) continue;
        sni.set(n, pair);
        dovecotSni.push({ name: n, ...pair });
      }
    } catch (e) {
      err.add(String(c?.names?.[0] ?? hostname), `certificate: ${errMsg(e)}`);
    }
  }
  const tlsDefault = defaultCert ?? { cert: C_SELF_SIGNED_CERT, key: C_SELF_SIGNED_KEY };
  const sniLines = [...sni.entries()].sort((x, y) => byString(x[0], y[0])).map(([n, p]) => `${n} ${p.key} ${p.cert}`);

  // ── Dovecot passdb / userdb / app passwords / Sieve ──
  const passwd: string[] = [];
  const users: string[] = [];
  const sieveFiles = new Map<string, string>();
  const aliasesByOwner = new Map<string, string[]>();
  for (const [addr, targets] of aliases) for (const t of targets) {
    if (!aliasesByOwner.has(t)) aliasesByOwner.set(t, []);
    aliasesByOwner.get(t)!.push(addr);
  }
  // Extra fields of the passwd-file are written with the userdb_ prefix:
  // Dovecot 2.3 ignores unprefixed extra fields as userdb fields (validated
  // on the Linux test host: plain quota_rule / sieve_before never reached the user).
  const sortedBoxes = [...boxes.values()].sort((x, y) => byString(x.m.address, y.m.address));
  for (const b of sortedBoxes) {
    const m = b.m;
    const extra: string[] = [];
    if (m.quotaMb !== null) extra.push(`userdb_quota_rule=*:storage=${m.quotaMb}M`);
    if (!m.sendEnabled) {
      // MA9: a mailbox that may not send makes the engine send nothing on its
      // behalf either: Sieve redirect prohibited (0 = refused, Pigeonhole >=
      // 0.3) and its personal script (vacation / notify) not run; the
      // location never exists, so delivery treats it as "no script".
      extra.push('userdb_sieve_max_redirects=0', `userdb_sieve=file:${SIEVE_DISABLED}`);
    }
    if (m.autoresponder && b.domainActive && m.receiveEnabled) {
      try {
        const rel = `sieve/${assertInt(m.id, 1, Number.MAX_SAFE_INTEGER, 'mailbox id')}.sieve`;
        sieveFiles.set(rel, renderVacationSieve(m.address, (aliasesByOwner.get(m.address) ?? []).filter(isActiveDomainOf).sort(byString), m.autoresponder));
        extra.push(`userdb_sieve_before=${C_LIVE}/${rel}`);
      } catch (e) {
        err.add(m.domain, `${m.localPart}: autoresponder: ${errMsg(e)}`);
      }
    }
    users.push(`${m.address}::${VMAIL_UID}:${VMAIL_GID}::${C_VMAIL}/${m.domain}/${m.localPart}::${extra.join(' ')}`);
    if (canLogin(b)) passwd.push(`${m.address}:${m.passwordHash}::::::`);
  }

  const appSlots: string[][] = [];
  const perUser = new Map<string, Array<{ hash: string; expires: number; id: number; nets: string[] }>>();
  for (const ap of state.appPasswords ?? []) {
    const dom = String(ap?.address ?? '').split('@')[1] ?? '';
    try {
      const address = assertAddress(ap.address);
      const b = boxes.get(address);
      if (!b || b.m.id !== ap.mailboxId) throw new RenderError('app password of an unknown mailbox');
      if (!canLogin(b)) continue;
      const expires = Date.parse(ap.expiresAt);
      if (!Number.isFinite(expires)) throw new RenderError('invalid app password expiry');
      if (expires <= ctx.now.getTime()) continue;
      assertPasswordHash(ap.passwordHash, 'SHA512-CRYPT');
      // MA6: only from the mail network, never from its gateway (= the Internet behind the userland proxy).
      const nets = networksExcluding(ap.allowNets ?? [], ctx.mailGateways);
      if (nets.length === 0) continue; // never an unrestricted credential
      if (!perUser.has(address)) perUser.set(address, []);
      perUser.get(address)!.push({ hash: ap.passwordHash, expires, id: Number(ap.id) || 0, nets });
    } catch (e) {
      err.add(dom, `app password: ${errMsg(e)}`);
    }
  }
  for (const [address, list] of [...perUser.entries()].sort((x, y) => byString(x[0], y[0]))) {
    list.sort((x, y) => y.expires - x.expires || y.id - x.id);
    list.slice(0, APP_PASSWORD_SLOTS).forEach((ap, i) => {
      if (!appSlots[i]) appSlots[i] = [];
      appSlots[i].push(`${address}:${ap.hash}::::::allow_real_nets=${ap.nets.join(',')}`);
    });
  }

  // ── DKIM (signing keys of active domains) ──
  const dkimKeys = new Map<string, string>();
  const signing: Array<{ domain: string; selector: string; file: string }> = [];
  for (const k of [...(state.dkim ?? [])].sort((x, y) => byString(`${x.domain}/${x.selector}`, `${y.domain}/${y.selector}`))) {
    if (!k.signing) continue;
    try {
      const domain = assertDomain(k.domain);
      if (!domains.get(domain)?.active) continue;
      const selector = assertSelector(k.selector);
      const rel = `${domain}/${selector}.key`;
      if (dkimKeys.has(rel)) throw new RenderError('duplicate DKIM selector');
      dkimKeys.set(rel, dkimKeyFile(k.privateKeyPem, k.algorithm));
      signing.push({ domain, selector, file: rel });
    } catch (e) {
      err.add(k?.domain, `DKIM: ${errMsg(e)}`);
    }
  }

  // ── forwarding limits (MA9) ──
  // Mail the engine re-sends out of the platform without SASL (forwarding,
  // alias expansion to an external target, external catch-all) is counted by
  // Rspamd against the hourly limit of the account, keyed by the local
  // recipient (a mailbox shares its SASL counter). '@domain' = the
  // catch-all; '-' = an existing address of such a domain (not the catch-all).
  const accountLimit = new Map<number, number>();
  for (const b of sortedBoxes) {
    if (b.m.sendPerHour === null) continue;
    const prev = accountLimit.get(b.m.accountId);
    accountLimit.set(b.m.accountId, prev === undefined ? b.m.sendPerHour : Math.min(prev, b.m.sendPerHour));
  }
  const isExternal = (t: string): boolean => !isActiveDomainOf(t);
  const domainAccount = new Map<string, number>();
  for (const d of state.domains) if (typeof d?.name === 'string') domainAccount.set(d.name.toLowerCase(), d.accountId);
  const fwdLimits = new Map<string, string>();
  for (const name of domainNames) {
    const d = domains.get(name)!;
    if (!d.active) continue;
    for (const b of boxesOf(name)) {
      const limit = accountLimit.get(b.m.accountId);
      if (limit === undefined || !b.m.receiveEnabled || !b.m.forward) continue;
      if (b.m.forward.targets.some((t) => t !== b.m.address && isExternal(t))) fwdLimits.set(b.m.address, String(limit));
    }
    const accountId = domainAccount.get(name);
    const domainLimit = accountId === undefined ? undefined : accountLimit.get(accountId);
    if (domainLimit === undefined) continue;
    for (const [addr, targets] of aliasesOf(name)) {
      if (targets.some((t) => t !== addr && isExternal(t))) fwdLimits.set(addr, String(domainLimit));
    }
    if (d.catchAll && isExternal(d.catchAll)) {
      fwdLimits.set(`@${name}`, String(domainLimit));
      for (const b of boxesOf(name)) if (!fwdLimits.has(b.m.address)) fwdLimits.set(b.m.address, '-');
      for (const [addr] of aliasesOf(name)) if (!fwdLimits.has(addr)) fwdLimits.set(addr, '-');
    }
  }
  const forwardLimits = [...fwdLimits.entries()].sort((x, y) => byString(x[0], y[0])).map(([k, v]) => line(k, v));

  // ── Rspamd ──
  const sendLimits = sortedBoxes.filter((b) => canLogin(b) && b.m.sendPerHour !== null).map((b) => line(b.m.address, String(b.m.sendPerHour)));
  const sizeLimits = domainNames.filter((n) => domains.get(n)!.active && domains.get(n)!.maxMb < maxSizeMb)
    .map((n) => line(n, String(domains.get(n)!.maxMb * 1048576)));
  const rspamd = renderRspamd({
    settings: { ...s, spamTagScore: tag, spamRejectScore: reject, maxMessageSizeMb: maxSizeMb },
    signing,
    signNetworks: relayClients.map((l) => l.split(' ')[0]),
    sendLimits,
    forwardLimits,
    sizeLimits,
    clamdMaxFileSizeMb: ctx.clamdMaxFileSizeMb ?? null,
  });

  // ── assemble ──
  const files = new Map<string, string>();
  files.set('postfix/main.cf', renderMainCf({ hostname, maxMessageBytes: maxSizeMb * 1048576, tls: tlsDefault, sni: sniLines.length > 0 }));
  files.set('postfix/master.cf', renderMasterCf());
  files.set('postfix/maps/virtual_domains', file('active mail domains', vDomains));
  files.set('postfix/maps/virtual_mailboxes', file('mailboxes of the active domains', vMailboxes));
  files.set('postfix/maps/virtual_aliases', file('aliases, forwarding, catch-all (last of each domain)', vAliases));
  files.set('postfix/maps/sender_login_maps', file('sender address → SASL logins allowed to use it (MA3)', senderLogin));
  files.set('postfix/maps/recipient_access', file('addresses refusing mail', recipientAccess));
  files.set('postfix/maps/sender_access', file('sender addresses whose sending is disabled', senderAccess));
  files.set('postfix/maps/sasl_access', file('SASL logins whose sending is disabled', saslAccess));
  files.set('postfix/cidr/relay_clients', file('site relay addresses trusted on the relay intake port (exact hosts, MA2)', relayClients));
  files.set('postfix/sni/tls_sni', file('SNI name → private key + chain (compiled with postmap -F)', sniLines));
  files.set('dovecot/dovecot.conf', renderDovecotConf({
    hostname,
    trustedNets,
    tls: tlsDefault,
    sni: dovecotSni.sort((x, y) => byString(x.name, y.name)),
    appPasswordSlots: appSlots.length,
    ipv6: ctx.mailSubnets.some((n) => n.includes(':')),
  }));
  files.set('dovecot/passwd', file('passdb: mailboxes allowed to log in', passwd));
  files.set('dovecot/users', file('userdb: every mailbox (delivery)', users));
  appSlots.forEach((lines, i) => files.set(`dovecot/apppasswords.${i}`, file(`webmail session credentials, slot ${i}`, lines)));
  for (const [rel, content] of [...sieveFiles.entries()].sort((x, y) => byString(x[0], y[0]))) files.set(rel, content);
  for (const [name, content] of rspamd) files.set(`rspamd/${name}`, content);

  const sorted = new Map([...files.entries()].sort((x, y) => byString(x[0], y[0])));
  const h = crypto.createHash('sha256');
  for (const [k, v] of sorted) h.update(`f\0${k}\0${v}\0`);
  for (const [k, v] of [...dkimKeys.entries()].sort((x, y) => byString(x[0], y[0]))) h.update(`k\0${k}\0${v}\0`);

  return {
    files: sorted,
    dkimKeys,
    mailboxes: sortedBoxes.map((b) => b.m.address),
    counts: { domains: activeDomains, mailboxes: boxes.size, aliases: renderedAliases },
    domainErrors: err.errors,
    fingerprint: h.digest('hex'),
  };
}

/** Mailboxes the previous render knew that the new one drops. */
export function removedMailboxes(previous: string[], next: string[]): string[] {
  const keep = new Set(next);
  return previous.filter((a) => !keep.has(a));
}

/**
 * Mass-removal guard (driver.ts rule): more than half of the known mailboxes
 * disappear. A floor of MASS_REMOVAL_MIN keeps the guard for what it is for (an
 * empty / truncated state built from a transient error) without blocking the
 * deletion of the only mailbox of a small platform.
 */
export const MASS_REMOVAL_MIN = 3;
export function isMassRemoval(previous: string[], next: string[]): boolean {
  const removed = removedMailboxes(previous, next).length;
  return removed >= MASS_REMOVAL_MIN && removed * 2 > previous.length;
}
