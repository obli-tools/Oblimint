import { isIP } from 'net';
import type { DesiredMailSettings } from '../../driver';
import { MAIL_REDIS_CONTAINER } from '../../../hosting/naming';
import { C_DKIM, REDIS_PORT } from './layout';
import { assertDomain, assertInt, assertNumber, assertSelector, formatCidr, parseCidr, RenderError } from './validate';

// ─────────────────────────────────────────────────────────────────────────────
// PURE Rspamd local.d/ files (module engine-postfix), mounted read-only at
// /etc/rspamd/local.d in oblimint-mail-rspamd. The image's override.d holds
// the static part (workers: proxy milter on :11332 for the mail network,
// controller on 127.0.0.1 only — never exposed, MA7; options: local_addrs =
// loopback only, so mail arriving from a Docker address is never "local").
//
//  - dkim_signing: authenticated senders and the site relay (sign_networks =
//    its exact addresses), header From domain, only the 'signing' keys;
//  - actions: add_header (tag) / reject (MA14); greylist on / off;
//  - antivirus: ClamAV of the shared scanner (clamd TCP) when configured,
//    virus ⇒ reject (MA14);
//  - oblimint_sendlimits.map / oblimint_fwdlimits.map / oblimint_sizelimits.map:
//    read by the image's rspamd.local.lua (hourly send limit per SASL user,
//    the same limit for mail re-sent outside by forwarding / aliases /
//    catch-all and by Sieve redirect, per-domain message size), reloaded by
//    Rspamd when they change.
// UCL expands $VARIABLES in double-quoted strings: every value interpolated
// here is from a whitelist without '$', quotes or backslashes.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * The map files rspamd.local.lua declares with rspamd_config:add_map (type
 * 'map', a file url): Rspamd watches them and reloads a changed one by
 * itself (measured on the Linux test host: a few seconds), so writing them needs NO
 * restart of oblimint-mail-rspamd (apply.ts). Keep in sync with
 * images/mail-rspamd/rspamd.local.lua.
 */
export const RSPAMD_WATCHED_MAPS = ['oblimint_sendlimits.map', 'oblimint_fwdlimits.map', 'oblimint_sizelimits.map'] as const;

export interface RspamdInput {
  settings: DesiredMailSettings;
  signing: Array<{ domain: string; selector: string; file: string }>;
  /** Host routes of the site relay ('a.b.c.d/32'). */
  signNetworks: string[];
  /** 'address perHour' lines. */
  sendLimits: string[];
  /** 'local-address perHour|-' lines: forwarding / alias / catch-all ('@domain') to external targets (MA9). */
  forwardLimits?: string[];
  /** 'domain bytes' lines. */
  sizeLimits: string[];
  /** settings scanner.maxFileSizeMb (MiB): clamd's StreamMaxLength / MaxFileSize. null ⇒ DEFAULT_CLAMD_MAX_FILE_MB. */
  clamdMaxFileSizeMb?: number | null;
}

/** settings scanner.maxFileSizeMb default (platformSettings), used when the value is unknown. */
export const DEFAULT_CLAMD_MAX_FILE_MB = 32;

const head = (what: string) => `# Generated by Oblimint (postfix-dovecot) — Rspamd ${what}. Do not edit: rewritten at every sync.`;

/** 'host:port' of clamd (container name or IP). */
export function parseClamdAddress(v: string): { host: string; port: number } {
  const m = /^(\[[0-9a-fA-F:]+\]|[A-Za-z0-9.-]{1,253}):(\d{1,5})$/.exec(String(v ?? '').trim());
  if (!m) throw new RenderError('invalid clamd address');
  const host = m[1].replace(/^\[|\]$/g, '');
  if (!isIP(host) && !/^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$/i.test(host)) throw new RenderError('invalid clamd address');
  return { host: m[1], port: assertInt(Number(m[2]), 1, 65535, 'clamd port') };
}

const num = (n: number) => String(Math.round(n * 100) / 100);

export function renderRspamd(input: RspamdInput): Map<string, string> {
  const s = input.settings;
  const tag = assertNumber(s.spamTagScore, 0, 1000, 'spam tag score');
  const reject = assertNumber(s.spamRejectScore, 0, 1000, 'spam reject score');
  const maxBytes = assertInt(s.maxMessageSizeMb, 1, 2048, 'maximum message size') * 1048576;
  const out = new Map<string, string>();

  out.set('redis.conf', [head('Redis'), `servers = "${MAIL_REDIS_CONTAINER}:${REDIS_PORT}";`, ''].join('\n'));

  const greylistAt = Math.max(0, Math.min(4, tag - 1));
  out.set('actions.conf', [
    head('actions (MA14: score >= reject ⇒ refused)'),
    `reject = ${num(reject)};`,
    `add_header = ${num(tag)};`,
    s.greylisting ? `greylist = ${num(greylistAt)};` : 'greylist = null;',
    'rewrite_subject = null;',
    '',
  ].join('\n'));

  out.set('greylist.conf', [head('greylisting'), `enabled = ${s.greylisting ? 'true' : 'false'};`, ''].join('\n'));

  out.set('milter_headers.conf', [
    head('headers'),
    'use = ["x-spam-status", "authentication-results"];',
    'skip_local = false;',
    'skip_authenticated = true;',
    'authenticated_headers = ["authentication-results"];',
    '',
  ].join('\n'));

  // expire: Bayes tokens get a TTL (100 days), so Redis can evict them before
  // it ever refuses a write (the hourly send-limit counters live there too).
  out.set('classifier-bayes.conf', [head('Bayes'), 'backend = "redis";', 'autolearn = true;', 'expire = 8640000;', ''].join('\n'));

  const av = [head('antivirus (shared scanner, clamd TCP)')];
  if (s.clamav && s.clamdAddress) {
    const c = parseClamdAddress(s.clamdAddress);
    // clamd refuses ("INSTREAM size limit exceeded" ⇒ CLAM_VIRUS_FAIL, message
    // delivered) or only partly scans anything above its own limit: never
    // send more than the scanner accepts. Larger messages are NOT
    // virus-scanned (spam checks still apply): residual gap, stated here.
    const clamdMb = assertInt(Math.round(input.clamdMaxFileSizeMb ?? DEFAULT_CLAMD_MAX_FILE_MB), 1, 512, 'scanner maximum file size');
    const avBytes = Math.min(maxBytes, clamdMb * 1048576);
    if (avBytes < maxBytes) av.push(`# Messages above ${clamdMb} MiB (settings scanner.maxFileSizeMb) are not sent to ClamAV.`);
    av.push(
      'clamav {',
      '  type = "clamav";',
      `  servers = "${c.host}:${c.port}";`,
      '  symbol = "CLAM_VIRUS";',
      '  action = "reject";',
      // single quotes: no UCL variable expansion; ${SCANNER} / ${VIRUS} are Rspamd's own placeholders
      `  message = '\${SCANNER}: virus found: "\${VIRUS}"';`,
      '  scan_mime_parts = false;',
      `  max_size = ${avBytes};`,
      '  timeout = 30;',
      '  retransmits = 2;',
      '  log_clean = false;',
      '}',
    );
  } else {
    av.push('# ClamAV disabled (settings mail.clamav off, or scanner not deployed).');
  }
  av.push('');
  out.set('antivirus.conf', av.join('\n'));

  const nets = input.signNetworks.map((n) => formatCidr(parseCidr(n)));
  const byDomain = new Map<string, Array<{ selector: string; file: string }>>();
  for (const k of input.signing) {
    const d = assertDomain(k.domain);
    const sel = assertSelector(k.selector);
    if (!/^[a-z0-9.-]+\/[a-z0-9-]+\.key$/.test(k.file)) throw new RenderError('invalid DKIM key file');
    if (!byDomain.has(d)) byDomain.set(d, []);
    byDomain.get(d)!.push({ selector: sel, file: k.file });
  }
  const dk = [
    head('DKIM signing (outgoing mail of authenticated mailboxes and of the site relay)'),
    'enabled = true;',
    'sign_authenticated = true;',
    'sign_local = false;',
    'sign_inbound = false;',
    `sign_networks = [${nets.map((n) => `"${n}"`).join(', ')}];`,
    'use_domain = "header";',
    'use_esld = false;',
    // MA3 / MA5: what may be signed is bounded by the envelope sender, which
    // Postfix checks against the SASL login (reject_sender_login_mismatch;
    // the null sender is refused on submission). An empty envelope must
    // never be signed (Rspamd would skip the header / envelope domain check),
    // and the header From domain must be the envelope domain. The image's
    // rspamd.local.lua (OBLIMINT_HDRFROM) additionally refuses an
    // authenticated message whose header From is not its envelope sender.
    // allow_username_mismatch stays true so an alias of the account on
    // another of its domains (in sender_login_maps) is still signed.
    'allow_envfrom_empty = false;',
    'allow_username_mismatch = true;',
    'allow_hdrfrom_mismatch = false;',
    'allow_hdrfrom_multiple = false;',
    'try_fallback = false;',
    'check_pubkey = false;',
    'domain {',
  ];
  for (const [d, keys] of [...byDomain.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    dk.push(`  "${d}" {`, '    selectors = [');
    for (const k of keys) dk.push(`      { path = "${C_DKIM}/${k.file}"; selector = "${k.selector}"; },`);
    dk.push('    ];', '  }');
  }
  dk.push('}', '');
  out.set('dkim_signing.conf', dk.join('\n'));

  const mapFile = (what: string, lines: string[], re: RegExp) => {
    for (const l of lines) if (!re.test(l)) throw new RenderError(`invalid ${what} entry`);
    return `${[head(what), ...lines].join('\n')}\n`;
  };
  out.set('oblimint_sendlimits.map', mapFile('hourly send limits (SASL user → messages per hour)', input.sendLimits, /^[a-z0-9._+-]+@[a-z0-9.-]+ \d{1,8}$/));
  out.set('oblimint_fwdlimits.map', mapFile('hourly limits of mail re-sent outside by forwarding / aliases / catch-all (local recipient → messages per hour, - = not counted)', input.forwardLimits ?? [], /^(?:[a-z0-9._+-]+|)@[a-z0-9.-]+ (?:\d{1,8}|-)$/));
  out.set('oblimint_sizelimits.map', mapFile('per-domain message size (domain → bytes)', input.sizeLimits, /^[a-z0-9.-]+ \d{1,12}$/));

  return new Map([...out.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)));
}
