import { MAIL_RSPAMD_CONTAINER } from '../../../hosting/naming';
import { C_POSTFIX_META, C_SPOOL, C_STATE, QUOTA_STATUS_PORT, RELAY_INTAKE_PORT, RSPAMD_MILTER_PORT, SIEVE_SUBMIT_PORT } from './layout';
import { assertHostname, assertInt, assertSafePath } from './validate';

// ─────────────────────────────────────────────────────────────────────────────
// PURE Postfix main.cf / master.cf (module engine-postfix). Security
// properties tested in render.test.ts (MA1–MA3):
//  - port 25 (MX): NO SASL at all; mynetworks = loopback hosts only;
//    reject_unauth_destination; only the active domains are accepted
//    (virtual_mailbox_domains) — no open relay (MA2);
//  - 587: STARTTLS mandatory (smtpd_tls_security_level=encrypt) and AUTH
//    only after TLS (smtpd_tls_auth_only) — 465: implicit TLS + AUTH;
//    both: reject_sender_login_mismatch (MA3), check_sasl_access /
//    check_sender_access for disabled sending, everything else refused;
//  - 10025 (site relay intake, never published): accepted ONLY from the exact
//    relay addresses (cidr table), no AUTH, everything else refused (MA2);
//  - Rspamd milter on every smtpd and on locally generated mail (DKIM signing
//    on the way out, SPF / DKIM / DMARC / spam / virus on the way in, MA14);
//    milter failure = temporary refusal (never unscanned / unsigned mail);
//  - recipient_access (reception disabled, alias without a live target) is
//    checked on EVERY smtpd (25, 587 / 465, 10025, Sieve 10026): a refused address is
//    never delivered, whoever submits the message;
//  - Dovecot quota-status refuses mail for a full mailbox at RCPT time.
//  - 127.0.0.1:10026 (SIEVE_SUBMIT_PORT, Sieve submission): what Dovecot LMTP sends
//    itself (vacation replies, Sieve redirects; submission_host in
//    confDovecot.ts). Bound to the container's loopback only (never on the
//    mail network, never published), loopback clients only, no AUTH; the
//    milter still scans / counts / limits it (Rspamd sees 127.0.0.1, the
//    "local pickup" case of rspamd.local.lua, MA9). It replaces sendmail ->
//    postdrop: under no-new-privileges postdrop loses its setgid bit and
//    vmail cannot write the maildrop queue. No new trust: port 25 already
//    relays for mynetworks (loopback hosts).
// Every map is lmdb compiled by oblimint-mail-ctl in the live generation
// ($config_directory), except relay_clients (cidr: read as is).
// ─────────────────────────────────────────────────────────────────────────────

export interface MainCfInput {
  hostname: string;
  maxMessageBytes: number;
  /** Container paths of the default certificate. */
  tls: { cert: string; key: string };
  /** An SNI table is rendered (postfix/sni/tls_sni). */
  sni: boolean;
}

const MAP = (name: string) => `lmdb:$config_directory/maps/${name}`;
const RELAY_CLIENTS = 'cidr:$config_directory/cidr/relay_clients';
/**
 * Submission (587 / 465) refuses the null envelope sender: Postfix skips
 * reject_sender_login_mismatch for MAIL FROM:<> (smtpd_null_access_lookup_key
 * '<>'), which would otherwise let any mailbox send with no checked identity
 * (and get another domain's header From signed). Inline map: nothing to postmap.
 */
export const NULL_SENDER_REJECT = 'inline:{ { <> = REJECT 5.7.1 A sender address is required for authenticated submission } }';

export function renderMainCf(input: MainCfInput): string {
  const hostname = assertHostname(input.hostname);
  const size = assertInt(input.maxMessageBytes, 1048576, 2048 * 1048576, 'maximum message size');
  const cert = assertSafePath(input.tls.cert, 'certificate path');
  const key = assertSafePath(input.tls.key, 'key path');
  const lines = [
    '# Generated by Oblimint (postfix-dovecot) — Postfix main.cf. Do not edit: rewritten at every sync.',
    'compatibility_level = 3.6',
    `myhostname = ${hostname}`,
    `mydomain = ${hostname}`,
    'myorigin = $myhostname',
    'smtpd_banner = $myhostname ESMTP',
    'biff = no',
    'append_dot_mydomain = no',
    'readme_directory = no',
    'recipient_delimiter = +',
    '',
    '# No local delivery: every hosted address is virtual (Dovecot LMTP).',
    'mydestination =',
    'local_recipient_maps =',
    'local_transport = error:5.1.1 local delivery is disabled',
    'alias_maps =',
    'alias_database =',
    'relay_domains =',
    'relayhost =',
    'inet_interfaces = all',
    'inet_protocols = all',
    '# MA2: only the container itself is a "trusted network" — never a subnet.',
    'mynetworks = 127.0.0.1/32 [::1]/128',
    '',
    '# Container layout (images/mail-postfix): queue and state on the data volume, logs on stdout.',
    `meta_directory = ${C_POSTFIX_META}`,
    `queue_directory = ${C_SPOOL}`,
    `data_directory = ${C_STATE}/postfix`,
    'maillog_file = /dev/stdout',
    '',
    `message_size_limit = ${size}`,
    'mailbox_size_limit = 0',
    'virtual_mailbox_limit = 0',
    '',
    `virtual_mailbox_domains = ${MAP('virtual_domains')}`,
    `virtual_mailbox_maps = ${MAP('virtual_mailboxes')}`,
    `virtual_alias_maps = ${MAP('virtual_aliases')}`,
    'virtual_transport = lmtp:unix:private/dovecot-lmtp',
    '',
    '# SASL through Dovecot; disabled globally, enabled on 587 / 465 only (master.cf). MA1: never on 25.',
    'smtpd_sasl_type = dovecot',
    'smtpd_sasl_path = private/auth',
    'smtpd_sasl_auth_enable = no',
    'smtpd_sasl_security_options = noanonymous, noplaintext',
    'smtpd_sasl_tls_security_options = noanonymous',
    'smtpd_sasl_authenticated_header = no',
    'broken_sasl_auth_clients = no',
    `smtpd_sender_login_maps = ${MAP('sender_login_maps')}`,
    '',
    'smtpd_helo_required = yes',
    'disable_vrfy_command = yes',
    'strict_rfc821_envelopes = yes',
    'smtpd_delay_reject = yes',
    'smtpd_client_connection_rate_limit = 60',
    'smtpd_client_auth_rate_limit = 30',
    'smtpd_client_restrictions =',
    'smtpd_helo_restrictions =',
    'smtpd_sender_restrictions = reject_non_fqdn_sender, reject_unknown_sender_domain',
    'smtpd_relay_restrictions = permit_mynetworks, reject_unauth_destination',
    `smtpd_recipient_restrictions = reject_non_fqdn_recipient, check_recipient_access ${MAP('recipient_access')}, permit_mynetworks, reject_unauth_destination, check_policy_service inet:127.0.0.1:${QUOTA_STATUS_PORT}`,
    'smtpd_data_restrictions = reject_unauth_pipelining',
    '',
    '# Submission (587 / 465), referenced from master.cf.',
    'oblimint_submission_client_restrictions = permit_sasl_authenticated, reject',
    '# MA3: the null sender (MAIL FROM:<>) skips reject_sender_login_mismatch: refused first on submission.',
    `oblimint_submission_sender_restrictions = reject_non_fqdn_sender, check_sender_access ${NULL_SENDER_REJECT}, reject_sender_login_mismatch, check_sasl_access ${MAP('sasl_access')}, check_sender_access ${MAP('sender_access')}, permit_sasl_authenticated, reject`,
    'oblimint_submission_relay_restrictions = permit_sasl_authenticated, reject',
    `oblimint_submission_recipient_restrictions = reject_non_fqdn_recipient, check_recipient_access ${MAP('recipient_access')}, permit_sasl_authenticated, reject`,
    `# Site relay intake (${RELAY_INTAKE_PORT}): exact relay addresses only, everything else refused (MA2).`,
    `oblimint_relay_client_restrictions = check_client_access ${RELAY_CLIENTS}, reject`,
    `oblimint_relay_sender_restrictions = check_sender_access ${MAP('sender_access')}, reject_non_fqdn_sender`,
    `oblimint_relay_relay_restrictions = check_client_access ${RELAY_CLIENTS}, reject`,
    `oblimint_relay_recipient_restrictions = reject_non_fqdn_recipient, check_recipient_access ${MAP('recipient_access')}, check_client_access ${RELAY_CLIENTS}, reject`,
    `# Sieve submission (127.0.0.1:${SIEVE_SUBMIT_PORT}, vacation / redirect from Dovecot LMTP): loopback clients only.`,
    `oblimint_sieve_recipient_restrictions = check_recipient_access ${MAP('recipient_access')}, permit_mynetworks, reject`,
    '',
    '# TLS: certificates copied by the panel (mail/certs), SNI table, TLS >= 1.2.',
    `smtpd_tls_chain_files = ${key}, ${cert}`,
    ...(input.sni ? ['tls_server_sni_maps = lmdb:$config_directory/sni/tls_sni'] : []),
    'smtpd_tls_security_level = may',
    'smtpd_tls_auth_only = yes',
    'smtpd_tls_protocols = >=TLSv1.2',
    'smtpd_tls_mandatory_protocols = >=TLSv1.2',
    'smtpd_tls_loglevel = 1',
    'smtpd_tls_received_header = yes',
    'smtpd_tls_session_cache_database = lmdb:${data_directory}/smtpd_scache',
    'smtp_tls_security_level = may',
    'smtp_tls_loglevel = 1',
    'smtp_tls_session_cache_database = lmdb:${data_directory}/smtp_scache',
    '',
    '# Rspamd (MA14): spam / virus / SPF / DKIM / DMARC in, DKIM signing out.',
    `smtpd_milters = inet:${MAIL_RSPAMD_CONTAINER}:${RSPAMD_MILTER_PORT}`,
    'non_smtpd_milters = $smtpd_milters',
    'milter_protocol = 6',
    'milter_default_action = tempfail',
    'milter_connect_timeout = 10s',
    'milter_content_timeout = 120s',
    'milter_mail_macros = i {mail_addr} {client_addr} {client_name} {auth_authen}',
  ];
  return `${lines.join('\n')}\n`;
}

/** master.cf: chroot off everywhere (the container is the jail), numeric ports. */
export function renderMasterCf(): string {
  const sub = (name: string, extra: string[]) => [
    `  -o syslog_name=postfix/${name}`,
    ...extra,
    '  -o smtpd_sasl_auth_enable=yes',
    '  -o smtpd_tls_auth_only=yes',
    '  -o smtpd_client_restrictions=$oblimint_submission_client_restrictions',
    '  -o smtpd_helo_restrictions=',
    '  -o smtpd_sender_restrictions=$oblimint_submission_sender_restrictions',
    '  -o smtpd_relay_restrictions=$oblimint_submission_relay_restrictions',
    '  -o smtpd_recipient_restrictions=$oblimint_submission_recipient_restrictions',
    '  -o milter_macro_daemon_name=ORIGINATING',
  ];
  const lines = [
    '# Generated by Oblimint (postfix-dovecot) — Postfix master.cf. Do not edit: rewritten at every sync.',
    '# service type  private unpriv  chroot  wakeup  maxproc command + args',
    '# MX: no SASL (MA1).',
    '25        inet  n       -       n       -       -       smtpd',
    '  -o smtpd_sasl_auth_enable=no',
    '# Submission: STARTTLS mandatory, then AUTH (MA1).',
    '587       inet  n       -       n       -       -       smtpd',
    ...sub('submission', ['  -o smtpd_tls_security_level=encrypt']),
    '# Submissions: implicit TLS, then AUTH (MA1).',
    '465       inet  n       -       n       -       -       smtpd',
    ...sub('submissions', ['  -o smtpd_tls_wrappermode=yes', '  -o smtpd_tls_security_level=encrypt']),
    `# Site relay intake: mail network only (never published), exact relay addresses (MA2).`,
    `${RELAY_INTAKE_PORT}     inet  n       -       n       -       -       smtpd`,
    '  -o syslog_name=postfix/relay',
    '  -o smtpd_sasl_auth_enable=no',
    '  -o smtpd_tls_security_level=none',
    '  -o mynetworks=127.0.0.1/32',
    '  -o smtpd_client_restrictions=$oblimint_relay_client_restrictions',
    '  -o smtpd_helo_restrictions=',
    '  -o smtpd_sender_restrictions=$oblimint_relay_sender_restrictions',
    '  -o smtpd_relay_restrictions=$oblimint_relay_relay_restrictions',
    '  -o smtpd_recipient_restrictions=$oblimint_relay_recipient_restrictions',
    '  -o milter_macro_daemon_name=ORIGINATING',
    '# Sieve submission (vacation, redirect) from Dovecot LMTP: container loopback only, never published.',
    `127.0.0.1:${SIEVE_SUBMIT_PORT} inet n       -       n       -       -       smtpd`,
    '  -o syslog_name=postfix/sieve',
    '  -o smtpd_sasl_auth_enable=no',
    '  -o smtpd_tls_security_level=none',
    '  -o mynetworks=127.0.0.1/32',
    '  -o smtpd_client_restrictions=permit_mynetworks,reject',
    '  -o smtpd_helo_restrictions=',
    '  -o smtpd_sender_restrictions=',
    '  -o smtpd_relay_restrictions=permit_mynetworks,reject',
    '  -o smtpd_recipient_restrictions=$oblimint_sieve_recipient_restrictions',
    'pickup    unix  n       -       n       60      1       pickup',
    'cleanup   unix  n       -       n       -       0       cleanup',
    'qmgr      unix  n       -       n       300     1       qmgr',
    'tlsmgr    unix  -       -       n       1000?   1       tlsmgr',
    'rewrite   unix  -       -       n       -       -       trivial-rewrite',
    'bounce    unix  -       -       n       -       0       bounce',
    'defer     unix  -       -       n       -       0       bounce',
    'trace     unix  -       -       n       -       0       bounce',
    'verify    unix  -       -       n       -       1       verify',
    'flush     unix  n       -       n       1000?   0       flush',
    'proxymap  unix  -       -       n       -       -       proxymap',
    'proxywrite unix -       -       n       -       1       proxymap',
    'smtp      unix  -       -       n       -       -       smtp',
    'relay     unix  -       -       n       -       -       smtp',
    '  -o syslog_name=postfix/$service_name',
    'showq     unix  n       -       n       -       -       showq',
    'error     unix  -       -       n       -       -       error',
    'retry     unix  -       -       n       -       -       error',
    'discard   unix  -       -       n       -       -       discard',
    'local     unix  -       n       n       -       -       local',
    'virtual   unix  -       n       n       -       -       virtual',
    'lmtp      unix  -       -       n       -       -       lmtp',
    'anvil     unix  -       -       n       -       1       anvil',
    'scache    unix  -       -       n       -       1       scache',
    'postlog   unix-dgram n  -       n       -       1       postlogd',
  ];
  return `${lines.join('\n')}\n`;
}
