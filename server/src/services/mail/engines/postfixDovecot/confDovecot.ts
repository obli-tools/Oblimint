import {
  APP_PASSWORD_SLOTS, C_DH_PARAMS, C_LIVE, C_SPOOL, C_STATE, C_VMAIL, QUOTA_STATUS_PORT, SIEVE_SUBMIT_PORT, VMAIL_GID, VMAIL_UID,
} from './layout';
import { assertHostname, assertInt, assertSafePath, parseCidr, formatCidr } from './validate';

// ─────────────────────────────────────────────────────────────────────────────
// PURE Dovecot 2.3 configuration (module engine-postfix). Included by the
// image's static /etc/dovecot/dovecot.conf (`!include <live>/dovecot/dovecot.conf`).
//
//  - MA1: disable_plaintext_auth + ssl = required: no password before TLS on
//    143 / 110 / 4190, except from login_trusted_networks = the mail network
//    subnets MINUS its gateway (the webmail talks plain IMAP / ManageSieve
//    inside the network and forwards the real client IP; behind Docker's
//    userland proxy public clients come from the gateway, which must never be
//    trusted — R-MAIL-CLIENTIP);
//  - MA6: passwords are checked against the passwd-files pushed by the panel
//    (no panel call per login); webmail session credentials live in
//    separate passwd-files with allow_real_nets = mail network (checked on
//    the REAL peer address, not the one a trusted proxy forwards), one file
//    per slot because a passwd-file keeps one line per user;
//  - quota (count backend) + quota-status for Postfix (refusal at RCPT);
//  - Sieve: panel scripts (autoresponder) come through the userdb field
//    sieve_before (precompiled in the live generation), personal ManageSieve
//    scripts stay under the mailbox home and still run afterwards;
//  - mail_location maildir under /var/vmail/<domain>/<local>/Maildir (CWP).
//  - mail Sieve sends itself (vacation replies, redirects) goes over SMTP to
//    Postfix's loopback-only Sieve submission listener (submission_host,
//    confPostfix.ts), never through /usr/sbin/sendmail: postdrop is setgid
//    postdrop, but the container runs with no-new-privileges, so the setgid
//    bit is ignored and vmail cannot write the maildrop queue (postdrop
//    retried until Dovecot killed sendmail after 30 s: vacation reply lost,
//    delivery held 30 s; seen on the Linux test host). Dovecot's program client also
//    drops every supplementary group before exec, so mail_access_groups
//    cannot help either.
// ─────────────────────────────────────────────────────────────────────────────

export interface DovecotConfInput {
  hostname: string;
  /** Networks allowed to forward the client IP and to use plaintext auth (gateway already excluded). */
  trustedNets: string[];
  tls: { cert: string; key: string };
  sni: Array<{ name: string; cert: string; key: string }>;
  appPasswordSlots: number;
  /** The mail network has an IPv6 subnet: also listen on "::" (an IPv4-only container may refuse it). */
  ipv6: boolean;
}

const D = `${C_LIVE}/dovecot`;

export function renderDovecotConf(input: DovecotConfInput): string {
  const hostname = assertHostname(input.hostname);
  const trusted = input.trustedNets.map((n) => formatCidr(parseCidr(n)));
  const slots = assertInt(input.appPasswordSlots, 0, APP_PASSWORD_SLOTS, 'app password slots');
  const cert = assertSafePath(input.tls.cert, 'certificate path');
  const key = assertSafePath(input.tls.key, 'key path');
  const passdb = (args: string) => ['passdb {', '  driver = passwd-file', `  args = username_format=%Lu ${args}`, '}'];
  const lines = [
    '# Generated by Oblimint (postfix-dovecot) — Dovecot configuration. Do not edit: rewritten at every sync.',
    'protocols = imap pop3 lmtp sieve',
    `listen = ${input.ipv6 ? '*, ::' : '*'}`,
    'base_dir = /run/dovecot',
    `state_dir = ${C_STATE}/dovecot`,
    'instance_name = oblimint-mail',
    'log_path = /dev/stderr',
    'info_log_path = /dev/stdout',
    'log_timestamp = "%Y-%m-%dT%H:%M:%SZ "',
    'login_greeting = Mail server ready.',
    '',
    '# Authentication (MA1, MA6)',
    'auth_mechanisms = plain login',
    'auth_username_format = %Lu',
    'auth_failure_delay = 2 secs',
    'auth_verbose = no',
    'auth_verbose_passwords = no',
    'disable_plaintext_auth = yes',
    `login_trusted_networks = ${trusted.join(' ')}`,
    ...passdb(`${D}/passwd`),
    ...Array.from({ length: slots }, (_, i) => passdb(`${D}/apppasswords.${i}`)).flat(),
    'userdb {',
    '  driver = passwd-file',
    `  args = username_format=%Lu ${D}/users`,
    `  default_fields = uid=${VMAIL_UID} gid=${VMAIL_GID} home=${C_VMAIL}/%d/%n`,
    '}',
    '',
    '# TLS (>= 1.2); per-name certificates by SNI',
    'ssl = required',
    'ssl_min_protocol = TLSv1.2',
    'ssl_prefer_server_ciphers = yes',
    `ssl_cert = <${cert}`,
    `ssl_key = <${key}`,
    `ssl_dh = <${C_DH_PARAMS}`,
    ...input.sni.flatMap((s) => [
      `local_name ${assertHostname(s.name)} {`,
      `  ssl_cert = <${assertSafePath(s.cert, 'certificate path')}`,
      `  ssl_key = <${assertSafePath(s.key, 'key path')}`,
      '}',
    ]),
    '',
    '# Mail storage (vmail 5000:5000, CWP layout)',
    `first_valid_uid = ${VMAIL_UID}`,
    `last_valid_uid = ${VMAIL_UID}`,
    `first_valid_gid = ${VMAIL_GID}`,
    `last_valid_gid = ${VMAIL_GID}`,
    `mail_uid = ${VMAIL_UID}`,
    `mail_gid = ${VMAIL_GID}`,
    `mail_home = ${C_VMAIL}/%d/%n`,
    `mail_location = maildir:${C_VMAIL}/%d/%n/Maildir`,
    'mail_plugins = $mail_plugins quota',
    'namespace inbox {',
    '  inbox = yes',
    '  separator = .',
    '  mailbox Drafts {',
    '    special_use = \\Drafts',
    '    auto = subscribe',
    '  }',
    '  mailbox Sent {',
    '    special_use = \\Sent',
    '    auto = subscribe',
    '  }',
    '  mailbox Junk {',
    '    special_use = \\Junk',
    '    auto = subscribe',
    '  }',
    '  mailbox Trash {',
    '    special_use = \\Trash',
    '    auto = subscribe',
    '  }',
    '}',
    `postmaster_address = postmaster@${hostname}`,
    `hostname = ${hostname}`,
    'lmtp_rcpt_check_quota = yes',
    '# Sieve vacation / redirect: SMTP to Postfix (loopback listener), never sendmail -> postdrop (see the header)',
    `submission_host = 127.0.0.1:${SIEVE_SUBMIT_PORT}`,
    '',
    '# Services',
    'service imap-login {',
    '  inet_listener imap {',
    '    port = 143',
    '  }',
    '  inet_listener imaps {',
    '    port = 993',
    '    ssl = yes',
    '  }',
    '}',
    'service pop3-login {',
    '  inet_listener pop3 {',
    '    port = 110',
    '  }',
    '  inet_listener pop3s {',
    '    port = 995',
    '    ssl = yes',
    '  }',
    '}',
    'service managesieve-login {',
    '  inet_listener sieve {',
    '    port = 4190',
    '  }',
    '}',
    'service lmtp {',
    `  unix_listener ${C_SPOOL}/private/dovecot-lmtp {`,
    '    mode = 0600',
    '    user = postfix',
    '    group = postfix',
    '  }',
    '}',
    'service auth {',
    `  unix_listener ${C_SPOOL}/private/auth {`,
    '    mode = 0660',
    '    user = postfix',
    '    group = postfix',
    '  }',
    '  unix_listener auth-userdb {',
    '    mode = 0600',
    '  }',
    '}',
    'service quota-status {',
    '  executable = quota-status -p postfix',
    '  inet_listener {',
    '    address = 127.0.0.1',
    `    port = ${QUOTA_STATUS_PORT}`,
    '  }',
    '  client_limit = 1',
    '}',
    'protocol imap {',
    '  mail_plugins = $mail_plugins imap_quota',
    '  mail_max_userip_connections = 20',
    '}',
    'protocol pop3 {',
    '  pop3_uidl_format = %08Xu%08Xv',
    '}',
    'protocol lmtp {',
    '  mail_plugins = $mail_plugins sieve',
    '}',
    '',
    'plugin {',
    '  quota = count:User quota',
    '  quota_vsizes = yes',
    '  quota_grace = 10%%',
    '  quota_status_success = DUNNO',
    '  quota_status_nouser = DUNNO',
    '  quota_status_overquota = "552 5.2.2 Mailbox is full"',
    '  sieve = file:~/sieve;active=~/.dovecot.sieve',
    '  sieve_max_script_size = 1M',
    '  sieve_max_actions = 32',
    '  sieve_max_redirects = 4',
    // MA9: a redirect leaves with the mailbox as envelope sender, so Rspamd
    // (client 127.0.0.1: Sieve submission listener, confPostfix.ts) counts it
    // against the mailbox's hourly limit.
    '  sieve_redirect_envelope_from = recipient',
    '  sieve_vacation_min_period = 1d',
    '  sieve_vacation_default_period = 7d',
    '  sieve_vacation_max_period = 30d',
    '}',
  ];
  return `${lines.join('\n')}\n`;
}
