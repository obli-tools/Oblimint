import type { DesiredAutoresponder } from '../../driver';
import { assertAddress, assertInt, RenderError } from './validate';

// ─────────────────────────────────────────────────────────────────────────────
// PURE Sieve autoresponder of one mailbox (module engine-postfix), run by
// Dovecot LMTP as a sieve_before script (the user's own ManageSieve script
// still runs afterwards: vacation keeps the implicit keep).
//
// Dates: compared on the "date" and "time" parts of currentdate in UTC
// (:zone "+0000") — exact, independent of the iso8601 rendering of the
// Pigeonhole version. startsAt inclusive, endsAt exclusive.
// Strings: quoted Sieve strings escape only '\' and '"'; no "variables"
// extension is required, so "${…}" in a subject / body stays literal text.
// The body is never logged (MA4).
// ─────────────────────────────────────────────────────────────────────────────

/** Sieve quoted string ('\' and '"' escaped). NUL / control characters refused (except \n and \t in a body). */
export function sieveString(value: string, multiline: boolean): string {
  if (typeof value !== 'string') throw new RenderError('invalid autoresponder text');
  const v = value.replace(/\r\n?/g, '\n');
  // eslint-disable-next-line no-control-regex
  const forbidden = multiline ? /[\x00-\x08\x0b-\x1f\x7f]/ : /[\x00-\x1f\x7f]/;
  if (forbidden.test(v)) throw new RenderError('invalid characters in the autoresponder');
  return `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function utcParts(iso: string): { date: string; time: string } {
  const t = Date.parse(iso);
  if (!Number.isFinite(t)) throw new RenderError('invalid autoresponder date');
  const d = new Date(t).toISOString(); // YYYY-MM-DDTHH:MM:SS.sssZ
  return { date: d.slice(0, 10), time: d.slice(11, 19) };
}

const cd = (cmp: string, part: 'date' | 'time', value: string) => `currentdate :zone "+0000" ${cmp} "${part}" "${value}"`;

export function renderVacationSieve(address: string, aliases: string[], ar: DesiredAutoresponder): string {
  assertAddress(address);
  aliases.forEach((a) => assertAddress(a, 'alias'));
  const days = assertInt(ar.intervalDays, 1, 30, 'autoresponder interval');
  if (String(ar.subject ?? '').length > 998 || String(ar.body ?? '').length > 20_000) throw new RenderError('autoresponder too long');
  const subject = sieveString(ar.subject ?? '', false);
  const body = sieveString(ar.body ?? '', true);
  const conds: string[] = ['not header :matches "X-Spam-Status" "Yes*"'];
  if (ar.startsAt) {
    const s = utcParts(ar.startsAt);
    conds.push(`anyof (${cd(':value "gt"', 'date', s.date)}, allof (${cd(':is', 'date', s.date)}, ${cd(':value "ge"', 'time', s.time)}))`);
  }
  if (ar.endsAt) {
    const e = utcParts(ar.endsAt);
    conds.push(`anyof (${cd(':value "lt"', 'date', e.date)}, allof (${cd(':is', 'date', e.date)}, ${cd(':value "lt"', 'time', e.time)}))`);
  }
  if (ar.startsAt && ar.endsAt && Date.parse(ar.endsAt) <= Date.parse(ar.startsAt)) throw new RenderError('autoresponder ends before it starts');
  const addresses = [address, ...aliases].map((a) => `"${a}"`).join(', ');
  return [
    '# Generated by Oblimint (postfix-dovecot) — autoresponder. Do not edit: rewritten at every sync.',
    'require ["vacation", "date", "relational"];',
    `if allof (${conds.join(',\n          ')}) {`,
    `  vacation :days ${days} :subject ${subject} :addresses [${addresses}]`,
    `    ${body};`,
    '}',
    '',
  ].join('\n');
}
