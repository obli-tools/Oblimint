// ─────────────────────────────────────────────────────────────────────────────
// postfix-dovecot engine — shared constants (module engine-postfix). The
// container-side paths are the contract with images/mail-postfix and
// images/mail-rspamd (their README / scripts use the very same values).
//
// Host tree (paths.ts, docs/P4-PLAN.md §4):
//   mail/data/postfix-dovecot/vmail/<domain>/<local>/Maildir   5000:5000 0700  → /var/vmail (rw)
//   mail/data/postfix-dovecot/spool/                            root 0755       → /var/spool/postfix (rw, Postfix queue)
//   mail/data/postfix-dovecot/state/                            root 0755       → /var/lib/oblimint-mail (rw: Postfix
//                                                                                  data_directory, Dovecot state, ctl outputs)
//   mail/config/postfix-dovecot/                                root 0700       → /etc/oblimint/mail (RO, generated)
//     rspamd/                                                   root 0755       → /etc/rspamd/local.d (RO, rspamd container)
//   mail/dkim/<domain>/<selector>.key                           0640 root:RSPAMD_GID → /etc/oblimint/dkim (RO, rspamd)
//   mail/certs/<name>/{fullchain,privkey}.pem                   (mail-dns-tls)  → /etc/oblimint/mail-certs (RO, engine)
//   mail/redis/                                                 REDIS_UID 0700  → /data (rw, redis)
// ─────────────────────────────────────────────────────────────────────────────

export const ENGINE = 'postfix-dovecot' as const;

/** vmail user of images/mail-postfix (owner of every Maildir; CWP uses the same ids). */
export const VMAIL_UID = 5000;
export const VMAIL_GID = 5000;
/** rspamd user / group of images/mail-rspamd (created with this id BEFORE the package; the build checks it). */
export const RSPAMD_UID = 11333;
export const RSPAMD_GID = 11333;
/** The redis container runs as this uid:gid (no passwd entry needed); owner of mail/redis. */
export const REDIS_UID = 6379;

// ── container paths (engine) ──
export const C_VMAIL = '/var/vmail';
export const C_SPOOL = '/var/spool/postfix';
export const C_STATE = '/var/lib/oblimint-mail';
/** Generated configuration, read-only bind of mail/config/postfix-dovecot. */
export const C_CONFIG = '/etc/oblimint/mail';
/** Certificates copied by mail-dns-tls, read-only bind of mail/certs. */
export const C_CERTS = '/etc/oblimint/mail-certs';
/**
 * Compiled configuration (tmpfs): oblimint-mail-ctl copies C_CONFIG into a new
 * generation, compiles the maps (postmap) and the Sieve scripts (sievec),
 * checks it (postfix check, doveconf) and only then points `live` at it.
 * /etc/postfix is a symlink to <live>/postfix in the image.
 */
export const C_LIVE = '/run/oblimint-mail/live';
/** Self-signed fallback certificate generated by the image at start (no certificate copied yet). */
export const C_SELF_SIGNED_CERT = '/run/oblimint-mail/selfsigned/fullchain.pem';
export const C_SELF_SIGNED_KEY = '/run/oblimint-mail/selfsigned/privkey.pem';
/** Postfix meta files (postfix-files, dynamicmaps.cf) moved out of /etc/postfix by the image. */
export const C_POSTFIX_META = '/usr/share/oblimint-mail/postfix-meta';
/** ffdhe2048 parameters baked in the image (Dovecot 2.3 ssl_dh). */
export const C_DH_PARAMS = '/usr/share/oblimint-mail/dh.pem';
/** Control script of the image (reload, queue, usage, version, ping…). */
export const MAIL_CTL = '/usr/local/bin/oblimint-mail-ctl';
/** Outputs of oblimint-mail-ctl too large for an exec stream (queue, usage), under C_STATE. */
export const C_CTL_OUT = `${C_STATE}/ctl`;
export const CTL_OUT_DIR = 'ctl';

// ── container paths (rspamd) ──
export const C_RSPAMD_LOCAL = '/etc/rspamd/local.d';
export const C_DKIM = '/etc/oblimint/dkim';
export const RSPAMD_CTL = '/usr/local/bin/oblimint-rspamd-ctl';
/** Milter of the rspamd proxy worker (MAIL_CORE_NETWORK only, never published). */
export const RSPAMD_MILTER_PORT = 11332;
export const REDIS_PORT = 6379;

// ── networks ──
/**
 * Back-end network of the engine (module engine-postfix): oblimint-mail,
 * oblimint-mail-rspamd, oblimint-mail-redis and, while ClamAV is on, the
 * shared scanner (clamd). The Rspamd milter (no authentication: whoever
 * reaches it can claim any SASL user and get a DKIM signature) and Redis
 * (send-limit counters, greylisting, Bayes) are reachable ONLY here — never
 * from MAIL_NETWORK, whose members include the Internet-facing webmail, the
 * edge, the panel and the site relay (also attached to every account network).
 * A plain bridge (not 'internal'): Rspamd needs DNS for SPF / DKIM / DMARC.
 */
export const MAIL_CORE_NETWORK = 'oblimint-mail-core';

// ── ports ──
/** Public ports published on config.hosting.mailBind (docs/P4-PLAN.md §4). */
export const PUBLIC_PORTS = [25, 465, 587, 143, 993, 110, 995, 4190] as const;
/** Relay intake (site relay → engine), mail network only, NEVER published. */
export const RELAY_INTAKE_PORT = 10025;
/**
 * Sieve submission (Dovecot LMTP -> Postfix smtpd: vacation replies, redirects),
 * bound to 127.0.0.1 inside oblimint-mail only, never published. Replaces
 * sendmail -> postdrop, which cannot write the maildrop queue under
 * no-new-privileges (setgid postdrop ignored).
 */
export const SIEVE_SUBMIT_PORT = 10026;
/** Dovecot quota-status policy service (Postfix check_policy_service), loopback only. */
export const QUOTA_STATUS_PORT = 12340;

// ── generated tree (relative to mail/config/postfix-dovecot) ──
export const MANIFEST_FILE = 'manifest.json';
/** Subdirectories the driver owns entirely (stale files inside are deleted). */
export const MANAGED_DIRS = ['postfix', 'dovecot', 'sieve', 'rspamd'] as const;
/** Maximum app password slots (one passwd-file per slot: Dovecot keeps the first line of a user per file). */
export const APP_PASSWORD_SLOTS = 8;

/** Files holding password hashes: root-only on the host (the container's root reads them). */
export function isSecretFile(rel: string): boolean {
  return rel === 'dovecot/passwd' || /^dovecot\/apppasswords\.\d+$/.test(rel);
}
