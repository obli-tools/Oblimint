import { MAIL_RELAY_ALIAS, MAIL_RELAY_PORT } from '../../hosting/naming';

// ─────────────────────────────────────────────────────────────────────────────
// PURE rendering of a site's msmtp configuration (docs/P4-PLAN.md §9.5, MA3,
// MA4) — msmtprc.test.ts. The file lands in the site's runtime directory
// (/etc/oblimint/site/msmtprc in the container, 0640 root:<account gid>) and
// is msmtp's SYSTEM configuration (/etc/msmtprc links to it, images/php):
//
//   host oblimint-mail-relay, port 2525, auth plain as site-<id>, tls off
//   (private account network), envelope sender FORCED (allow_from_override
//   off), log to stderr (the site's error log), never syslog.
//
// Every value is validated (no whitespace, quote, '#' or line break: msmtp
// would read the rest as another directive); an invalid input throws instead
// of producing a file.
// ─────────────────────────────────────────────────────────────────────────────

export interface MsmtprcInput {
  /** SASL user of the site (site-<id>). */
  username: string;
  /** Clear relay credential (random, generated by the panel). */
  password: string;
  /** Envelope sender (an allowed address of the account). */
  from: string;
  /** Defaults: MAIL_RELAY_ALIAS / MAIL_RELAY_PORT. */
  host?: string;
  port?: number;
}

export const RELAY_USERNAME_RE = /^site-[1-9][0-9]{0,9}$/;
/** Credentials generated by the panel are base64url (generateMailPassword). */
export const RELAY_PASSWORD_RE = /^[A-Za-z0-9_-]{16,128}$/;
/** Strict address: lower-case, no quotes / spaces / control characters (also valid in policy.json and a From header). */
export const SAFE_ADDRESS_RE = /^[a-z0-9!#$%&'*+/=?^_{|}~.-]{1,64}@(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$/;
const HOST_RE = /^[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?$/;

export class MsmtprcError extends Error {
  constructor(public field: string) {
    super(`invalid msmtprc value: ${field}`);
    this.name = 'MsmtprcError';
  }
}

/** Is this address safe for msmtprc / the relay policy (and short enough)? */
export function isSafeAddress(addr: string): boolean {
  return addr.length <= 254 && SAFE_ADDRESS_RE.test(addr) && !addr.includes('#');
}

export function renderMsmtprc(input: MsmtprcInput): string {
  const host = input.host ?? MAIL_RELAY_ALIAS;
  const port = input.port ?? MAIL_RELAY_PORT;
  if (!RELAY_USERNAME_RE.test(input.username)) throw new MsmtprcError('username');
  if (!RELAY_PASSWORD_RE.test(input.password)) throw new MsmtprcError('password');
  if (!isSafeAddress(input.from)) throw new MsmtprcError('from');
  if (!HOST_RE.test(host)) throw new MsmtprcError('host');
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new MsmtprcError('port');
  return [
    '# Generated by Oblimint: do not edit (rewritten by the panel).',
    '# PHP mail() → the authenticated site relay of the platform.',
    'defaults',
    'syslog off',
    'logfile -',
    'timeout 30',
    '',
    'account oblimint',
    `host ${host}`,
    `port ${port}`,
    'protocol smtp',
    'tls off',
    'tls_starttls off',
    'auth plain',
    `user ${input.username}`,
    `password ${input.password}`,
    `from ${input.from}`,
    'allow_from_override off',
    'set_from_header auto',
    '',
    'account default : oblimint',
    '',
  ].join('\n');
}
