func TestRenderSegmentsProperties(t *testing.T) {
	out := renderSegments(mustSeg(t, segFixture(segModeEnforce)))
	// Atomic replacement: create (no-op if present), delete, recreate — one nft -f transaction.
	if !strings.HasPrefix(out, "# Generated by oblimint-hostd") || !strings.Contains(out, "table bridge oblimint_seg\ndelete table bridge oblimint_seg\ntable inet oblimint_seghost\ndelete table inet oblimint_seghost\ntable bridge oblimint_seg {") {
		t.Fatalf("not an atomic replacement:\n%s", out)
	}
	// Frames of non-managed bridges are accepted first; the default verdict is the last rule.
	fwd := out[strings.Index(out, "chain forward"):]
	lines := strings.Split(strings.TrimSpace(fwd), "\n")
	if !strings.Contains(lines[2], "meta ibrname != @fabrics accept") {
		t.Errorf("first rule must skip the other bridges: %q", lines[2])
	}
	if !strings.Contains(lines[len(lines)-3], `counter name "dropped" drop`) {
		t.Errorf("last rule must be the drop: %q", lines[len(lines)-3])
	}
	// Replies: swapped addresses, sport; TCP never a bare SYN.
	if !strings.Contains(out, "10.224.0.5 . 10.224.0.2 . tcp . 8080") {
		t.Error("reply tuple missing")
	}
	if strings.Count(out, "10.224.0.2 . 10.224.0.5 . tcp . 8080") != 1 {
		t.Error("duplicate flow rendered twice")
	}
	if !strings.Contains(out, "tcp flags & (syn | ack) != syn") {
		t.Error("bare SYN not excluded from replies")
	}
	// No accept-all, no rule touching the bridge itself (no iif/oif of the bridge device).
	for _, bad := range []string{"iifname", "oifname", "policy drop"} {
		if strings.Contains(out, bad) {
			t.Errorf("unexpected %q in the ruleset", bad)
		}
	}
	// Monitor never drops.
	mon := renderSegments(mustSeg(t, segFixture(segModeMonitor)))
	if strings.Contains(mon, " drop\n") {
		t.Errorf("monitor mode must not drop:\n%s", mon)
	}
	if !strings.Contains(mon, `log prefix "oblimint-seg "`) {
		t.Error("monitor mode must log")
	}
	// Off: the table is deleted, nothing recreated.
	off := renderSegments(mustSeg(t, segFixture(segModeOff)))
	if strings.Contains(off, "chain") || !strings.Contains(off, "delete table bridge oblimint_seg") || !strings.Contains(off, "delete table inet oblimint_seghost") {
		t.Errorf("off mode:\n%s", off)
	}
}

func TestSegmentValidation(t *testing.T) {
	ok := segFixture(segModeEnforce)
	cases := map[string]func(s *SegmentState){
		"mode":             func(s *SegmentState) { s.Mode = "drop" },
		"empty mode":       func(s *SegmentState) { s.Mode = "" },
		"long bridge":      func(s *SegmentState) { s.Bridges[0].Name = "abcdefghijklmnop" },
		"bridge quote":     func(s *SegmentState) { s.Bridges[0].Name = `om"f1` },
		"bridge space":     func(s *SegmentState) { s.Bridges[0].Name = "om f1" },
		"bridge brace":     func(s *SegmentState) { s.Bridges[0].Name = "omf1}" },
		"bridge empty":     func(s *SegmentState) { s.Bridges[0].Name = "" },
		"bridge dup":       func(s *SegmentState) { s.Bridges = append(s.Bridges, s.Bridges[0]) },
		"account":          func(s *SegmentState) { s.Bridges[0].AccountID = 0 },
		"fabric":           func(s *SegmentState) { s.Bridges[0].Fabric = "middle" },
		"fabric isolation": func(s *SegmentState) { s.Bridges[0].Isolation = segIsolateList },
		"platform account": func(s *SegmentState) { s.Bridges[0].Fabric = segFabricPlat },
		"platform isolation": func(s *SegmentState) {
			s.Bridges[0] = SegmentBridge{Name: "omf1", Fabric: segFabricPlat, Isolation: "none"}
		},
		"restricted ipv6": func(s *SegmentState) { s.Restricted = []string{"fd00::2"} },
		"restricted cidr": func(s *SegmentState) { s.Restricted = []string{"172.20.0.0/16"} },
		"host on fabric":  func(s *SegmentState) { s.Host = []SegmentHostAccess{{Bridge: "omf1", Protocol: "tcp", Port: 443}} },
		"host fabric src": func(s *SegmentState) {
			s.Host = []SegmentHostAccess{{Bridge: "omf1", Src: "fd00::1", Protocol: "tcp", Port: 443}}
		},
		"host unlisted": func(s *SegmentState) {
			s.Host = []SegmentHostAccess{{Bridge: "br-ffffffffffff", Protocol: "tcp", Port: 443}}
		},
		"host bad src":      func(s *SegmentState) { platHost(s, SegmentHostAccess{Src: "10.0.0.0/8", Protocol: "tcp", Port: 443}) },
		"host bad protocol": func(s *SegmentState) { platHost(s, SegmentHostAccess{Protocol: "icmp", Port: 1}) },
		"host port 0":       func(s *SegmentState) { platHost(s, SegmentHostAccess{Protocol: "tcp", Port: 0}) },
		"too many restricted": func(s *SegmentState) {
			s.Restricted = make([]string, maxSegRestrict+1)
		},
		"unlisted bridge": func(s *SegmentState) { s.Allow[0].Bridge = "omf9" },
		"ipv6 src":        func(s *SegmentState) { s.Allow[0].Src = "fd00::2" },
		"mapped dst":      func(s *SegmentState) { s.Allow[0].Dst = "::ffff:10.224.0.5" },
		"cidr src":        func(s *SegmentState) { s.Allow[0].Src = "10.224.0.0/24" },
		"garbage dst":     func(s *SegmentState) { s.Allow[0].Dst = "10.224.0.5; flush ruleset" },
		"same addr":       func(s *SegmentState) { s.Allow[0].Dst = s.Allow[0].Src },
		"protocol":        func(s *SegmentState) { s.Allow[0].Protocol = "icmp" },
		"port 0":          func(s *SegmentState) { s.Allow[0].Port = 0 },
		"port 65536":      func(s *SegmentState) { s.Allow[0].Port = 65536 },
		"too many bridges": func(s *SegmentState) {
			s.Bridges = nil
			for i := 0; i <= maxSegBridges; i++ {
				s.Bridges = append(s.Bridges, SegmentBridge{Name: fmt.Sprintf("omf%d", i+1), AccountID: int64(i + 1), Fabric: "front"})
			}
			s.Allow = nil
		},
		"too many flows": func(s *SegmentState) {
			s.Allow = make([]SegmentFlow, maxSegFlows+1)
		},
	}
	for name, mutate := range cases {
		s := segFixture(segModeEnforce)
		s.Bridges = append([]SegmentBridge(nil), ok.Bridges...)
		s.Allow = append([]SegmentFlow(nil), ok.Allow...)
		mutate(&s)
		_, err := s.validate()
		var ae *apiError
		if !errors.As(err, &ae) || ae.Status != http.StatusBadRequest {
			t.Errorf("%s: want 400, got %v", name, err)
		}
	}
	// The limits themselves are accepted.
	big := SegmentState{Mode: segModeEnforce}
	for i := 0; i < maxSegBridges; i++ {
		big.Bridges = append(big.Bridges, SegmentBridge{Name: fmt.Sprintf("omf%d", i+1), AccountID: int64(i + 1), Fabric: "front"})
	}
	for i := 0; i < maxSegFlows; i++ {
		big.Allow = append(big.Allow, SegmentFlow{Bridge: "omf1", Src: "10.224.0.2", Dst: fmt.Sprintf("10.%d.%d.%d", 225+i/65536, (i/256)%256, i%256), Protocol: "tcp", Port: 80})
	}
	start := time.Now()
	r, err := big.validate()
	if err != nil {
		t.Fatalf("limits: %v", err)
	}
	out := renderSegments(r)
	if len(r.Flows) != maxSegFlows || strings.Count(out, ". tcp . 80") != 2*maxSegFlows {
		t.Errorf("flows rendered: %d", strings.Count(out, ". tcp . 80"))
	}
	if time.Since(start) > 10*time.Second {
		t.Errorf("validate + render of the limits took %s", time.Since(start))
	}
}

func TestSegmentManagerApplyPersistRestore(t *testing.T) {
	nft := &fakeNft{available: true}
	state := filepath.Join(t.TempDir(), "run", "hostd-segments.json")
	m := newSegmentManager(nft, state)
	m.now = func() time.Time { return fwNow }
	m.counter = func(context.Context) (string, error) {
		return "table bridge oblimint_seg {\n\tcounter dropped {\n\t\tpackets 42 bytes 2520\n\t}\n}\n", nil
	}

	st := m.Status()
	if st.Mode != segModeOff || st.Bridges != 0 || st.Dropped != nil || st.Backend != "nftables" {
		t.Fatalf("initial status: %+v", st)
	}
	if err := m.Apply(context.Background(), segFixture(segModeEnforce)); err != nil {
		t.Fatal(err)
	}
	want := renderSegments(mustSeg(t, segFixture(segModeEnforce)))
	if nft.last() != want {
		t.Fatalf("applied ruleset differs")
	}
	st = m.Status()
	if st.Mode != segModeEnforce || st.Bridges != 3 || st.Rules != 5 || st.Dropped == nil || *st.Dropped != 42 || st.LastApplyAt == nil || st.LastApplyError != nil {
		t.Fatalf("status after apply: %+v", st)
	}
	info, err := os.Stat(state)
	if err != nil {
		t.Fatalf("state not persisted: %v", err)
	}
	if info.Mode().Perm()&0o077 != 0 && os.PathSeparator == '/' {
		t.Errorf("state file mode %v", info.Mode().Perm())
	}

	// A refused ruleset keeps the previous policy (applied + persisted), the error is visible.
	before, _ := os.ReadFile(state)
	nft.fail = errors.New("nft -f: Error: syntax error")
	err = m.Apply(context.Background(), segFixture(segModeMonitor))
	var ae *apiError
	if !errors.As(err, &ae) || ae.Status != http.StatusBadGateway || ae.Code != codeApplyFailed {
		t.Fatalf("want 502 applyFailed, got %v", err)
	}
	st = m.Status()
	if st.Mode != segModeEnforce || st.LastApplyError == nil {
		t.Fatalf("status after a refused apply: %+v", st)
	}
	after, _ := os.ReadFile(state)
	if string(before) != string(after) {
		t.Error("a refused policy must not be persisted")
	}
	// An invalid state is refused before nft (400), nothing changes.
	nft.fail = nil
	n := nft.count()
	if err := m.Apply(context.Background(), SegmentState{Mode: "bogus"}); err == nil {
		t.Fatal("invalid state accepted")
	}
	if nft.count() != n {
		t.Error("nft called for an invalid state")
	}

	// Restart: a new manager re-applies the persisted policy.
	nft2 := &fakeNft{available: true}
	m2 := newSegmentManager(nft2, state)
	if err := m2.Restore(context.Background()); err != nil {
		t.Fatal(err)
	}
	if nft2.last() != want {
		t.Fatalf("restored ruleset differs:\n%s", nft2.last())
	}
	if st := m2.Status(); st.Mode != segModeEnforce || st.Rules != 5 || st.Dropped != nil {
		t.Fatalf("restored status: %+v", st)
	}

	// Mode off: the table is deleted, status reports off without counters.
	if err := m2.Apply(context.Background(), SegmentState{Mode: segModeOff}); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(nft2.last(), "delete table bridge oblimint_seg") || strings.Contains(nft2.last(), "chain") {
		t.Fatalf("off ruleset:\n%s", nft2.last())
	}
	if st := m2.Status(); st.Mode != segModeOff || st.Rules != 0 || st.Bridges != 0 {
		t.Fatalf("off status: %+v", st)
	}
}

func TestSegmentManagerRestoreEdgeCases(t *testing.T) {
	dir := t.TempDir()
	// Missing file: nothing to do.
	m := newSegmentManager(&fakeNft{available: true}, filepath.Join(dir, "none.json"))
	if err := m.Restore(context.Background()); err != nil {
		t.Fatal(err)
	}
	// Corrupt / invalid files are reported, nothing applied.
	for name, body := range map[string]string{"corrupt.json": "{", "invalid.json": `{"mode":"enforce","bridges":[{"name":"bad name","accountId":1,"fabric":"front"}],"allow":[]}`} {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
		nft := &fakeNft{available: true}
		if err := newSegmentManager(nft, p).Restore(context.Background()); err == nil || nft.count() != 0 {
			t.Errorf("%s: want an error and no apply (err=%v, applies=%d)", name, err, nft.count())
		}
	}
	// No nft at all: 501, status backend none.
	nm := newSegmentManager(nil, "")
	if err := nm.Apply(context.Background(), segFixture(segModeEnforce)); !errors.Is(err, errUnsupported) {
		t.Fatalf("want errUnsupported, got %v", err)
	}
	if st := nm.Status(); st.Backend != "none" || st.LastApplyError == nil {
		t.Fatalf("status without nft: %+v", st)
	}
}

